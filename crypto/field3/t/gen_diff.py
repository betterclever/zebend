#!/usr/bin/env python3
"""Writes t/diff3.bend: a differential test of fp3/fq3 against the previous pure-Bend
fields (research/fast/pure) and against themselves (sqr = mul(x, x), mul(add_nr(x, y), y) =
mul(add(x, y), y)), over N random pairs per field, plus an order-independent XOR
digest of every result that rust/ recomputes with pasta_curves."""
import pathlib
OPS = ["mul", "sqr", "add", "sub", "lazy"]
out = ['''# GENERATED by t/gen_diff.py. Do not edit.
import Base
import ../../../zcash/halo2/lib/words.bend as Wd
import ../fp3.bend as Fp
import ../fq3.bend as Fq
import ../../../research/fast/pure/fp32.bend as OFp
import ../../../research/fast/pure/fq32.bend as OFq

def xs(+s: U32) -> U32:
  +a = (s .^. (s << 13n) : U32)
  +b = (a .^. (a >> 17n) : U32)
  (b .^. (b << 5n) : U32)

# Mismatch count plus XOR digest (8 words).
type Acc is Data:
  Acc{bad: U32, d0: U32, d1: U32, d2: U32, d3: U32, d4: U32, d5: U32, d6: U32, d7: U32}

def mix(a: Acc, w: Wd.W, +ok: Bool) -> Acc:
  Acc{+bad, +d0, +d1, +d2, +d3, +d4, +d5, +d6, +d7} = a
  Wd.W{+w0, +w1, +w2, +w3, +w4, +w5, +w6, +w7} = w
  Acc{(bad + Bool.to_u32(Bool.not(ok)) : U32), (d0 .^. w0 : U32), (d1 .^. w1 : U32), (d2 .^. w2 : U32), (d3 .^. w3 : U32), (d4 .^. w4 : U32), (d5 .^. w5 : U32), (d6 .^. w6 : U32), (d7 .^. w7 : U32)}

def join(a: Acc, b: Acc) -> Acc:
  Acc{+ab, +a0, +a1, +a2, +a3, +a4, +a5, +a6, +a7} = a
  Acc{+bb, +b0, +b1, +b2, +b3, +b4, +b5, +b6, +b7} = b
  Acc{(ab + bb : U32), (a0 .^. b0 : U32), (a1 .^. b1 : U32), (a2 .^. b2 : U32), (a3 .^. b3 : U32), (a4 .^. b4 : U32), (a5 .^. b5 : U32), (a6 .^. b6 : U32), (a7 .^. b7 : U32)}

def acc0() -> Acc:
  Acc{0, 0, 0, 0, 0, 0, 0, 0, 0}

# Random 256-bit value with the top word masked below 2^30 (so < 2^254 < m): the
# same inputs rust/ draws.
def rw(+s: U32) -> Wd.W:
  +s1 = xs(s)
  +s2 = xs(s1)
  +s3 = xs(s2)
  +s4 = xs(s3)
  +s5 = xs(s4)
  +s6 = xs(s5)
  +s7 = xs(s6)
  +s8 = xs(s7)
  Wd.W{s1, s2, s3, s4, s5, s6, s7, (s8 .&. 1073741823 : U32)}

def next8(+s: U32) -> U32:
  xs(xs(xs(xs(xs(xs(xs(xs(s))))))))
''']
for F, O in (("Fp", "OFp"), ("Fq", "OFq")):
    f = F.lower()
    out.append(f'''
def {f}_one(+x: {F}.{F}, +y: {F}.{F}, +ox: {O}.{F}, +oy: {O}.{F}, a: Acc) -> Acc:
  +m = {F}.mul(x, y)
  +q = {F}.sqr(x)
  +ad = {F}.add(x, y)
  +sb = {F}.sub(x, y)
  +lz = {F}.mul({F}.add_nr(x, y), y)
  +wm = {F}.to_words(m)
  +wq = {F}.to_words(q)
  +wa = {F}.to_words(ad)
  +ws = {F}.to_words(sb)
  +a1 = mix(a, wm, Wd.is_eq(wm, {O}.to_words({O}.mul(ox, oy))))
  +a2 = mix(a1, wq, Bool.and(Wd.is_eq(wq, {O}.to_words({O}.sqr(ox))), Wd.is_eq(wq, {F}.to_words({F}.mul(x, x)))))
  +a3 = mix(a2, wa, Wd.is_eq(wa, {O}.to_words({O}.add(ox, oy))))
  +a4 = mix(a3, ws, Wd.is_eq(ws, {O}.to_words({O}.sub(ox, oy))))
  mix(a4, {F}.to_words(lz), Wd.is_eq({F}.to_words(lz), {F}.to_words({F}.mul(ad, y))))

def {f}_pair(+wx: Wd.W, +wy: Wd.W, a: Acc) -> Acc:
  {f}_one({F}.from_words(wx), {F}.from_words(wy), {O}.from_words(wx), {O}.from_words(wy), a)

def {f}_run(n: Nat, +s: U32, a: Acc) -> Acc:
  match n:
    case 0n:
      a
    case 1n+k:
      +t = next8(s)
      {f}_run(k, next8(t), {f}_pair(rw(s), rw(t), a))

def {f}_par(+d: Nat, +seed: U32, +n: Nat) -> Acc:
  match d:
    case 0n:
      {f}_run(n, (seed * 2654435761 + 12345 : U32), acc0())
    case 1n+p:
      a b = {f}_par(p, (seed * 2 : U32), n) {f}_par(p, (seed * 2 + 1 : U32), n)
      join(a, b)
''')
out.append('''
def show(a: Acc) -> String:
  Acc{+bad, +d0, +d1, +d2, +d3, +d4, +d5, +d6, +d7} = a
  "mismatches " ++ U32.show(bad) ++ " digest " ++ Wd.hex(Wd.W{d0, d1, d2, d3, d4, d5, d6, d7})

def main() -> IO(Unit):
  do IO<Unit>:
    IO.print("Fp " ++ show(fp_par(6n, 1, 15625n)))
    IO.print("Fq " ++ show(fq_par(6n, 2, 15625n)))
''')
pathlib.Path(__file__).resolve().parent.joinpath("diff3.bend").write_text("".join(out))
print("wrote t/diff3.bend")
