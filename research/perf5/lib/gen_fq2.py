#!/usr/bin/env python3
"""gen_fq2.py: writes lib/fq2.bend, two-lane Vesta-base-field (Fq) arithmetic and point
decompression for perf5.

A square root is ~224 dependent squarings, so one decompression leaves most of the core idle
(each field op waits on the previous one). Two independent decompressions in lockstep, with the
two lanes' instructions interleaved in one function body, let the core overlap them.

Nothing here is new arithmetic. Every function is a text copy of an existing, tested one:
  sqr2 / mul2     fq64.bend's sqr_d / mul, once per lane (lane B's variables renamed), lines
                  interleaved. Each lane computes exactly what sqr_d / mul compute.
  pow_t2          decomp/fq_sqrt.bend's pow_t with B.sqr / B.mul / B.sqr_n -> sqr2 / mul2 / sqr_n2.
  root2           SQ.root on each lane (pow_t2, then SQ.common per lane).
  decompress2     decomp/vesta_dec.bend's decompress_ct on each lane (dec_ct_fin per lane).
decompress_ct is tested equal to decompress (decomp/README.md), so decompress2 returns, per lane,
what decompress returns.

  python3 lib/gen_fq2.py
"""
import pathlib
import re

here = pathlib.Path(__file__).resolve().parent
Z = here.parents[2]
fq = (Z / "crypto/field3/fq64.bend").read_text()
sq = (Z / "research/decomp/fq_sqrt.bend").read_text()


def body(src, name):
    m = re.search(rf"^def {name}\(.*?\n(.*?)\n\n", src, re.S | re.M)
    return m.group(1).split("\n")


def lane(lines, ren):
    """lines of one generated function: destructures, lets, final Fq{...} literal."""
    pat = re.compile(r"\b(" + "|".join(ren) + r")(\d*)\b")
    return [pat.sub(lambda m: ren[m.group(1)] + m.group(2), l) for l in lines]


def two_lane(name, src_name, params, heads, renames):
    a = body(fq, src_name)
    b = lane(a, renames)
    da = [l for l in a if l.startswith("  Fq{+")]
    db = [l for l in b if l.startswith("  Fq{+")]
    la = [l for l in a if l.startswith("  +")]
    lb = [l for l in b if l.startswith("  +")]
    ra, rb = a[-1].strip(), b[-1].strip()
    assert ra.startswith("Fq{") and rb.startswith("Fq{") and len(la) == len(lb)
    # each pair, then its two lanes' limbs (Bend matches a binder only before any later one)
    out = [f"def {name}({params}) -> Fq2:"]
    ds = [l.replace("  Fq{", "  B.Fq{", 1) for l in da + db]
    for k, h in enumerate(heads):
        out += [h] + [l for l in ds if l.endswith(" = " + h.split("{+")[1].split(",")[0]) or l.endswith(" = " + h.split(", +")[1].split("}")[0])]
    for x, y in zip(la, lb):
        out += [x, y]
    out.append(f"  Fq2{{B.{ra}, B.{rb}}}")
    return "\n".join(out) + "\n"


def sqr_n2_inline():
    """sqr_n2 with sqr2's body in the loop itself: the 224-step chain of a square root then runs
    in one function (a call per step costs ~15%: arguments in, results out through memory)."""
    s = two_lane("sqr2", "sqr_d", "p: Fq2", ["  Fq2{+a, +c} = p"], {"a": "c", "v": "u"}).rstrip("\n").split("\n")
    head, steps, res = s[1], s[2:-1], s[-1].strip()
    assert head == "  Fq2{+a, +c} = p" and res.startswith("Fq2{")
    return "\n".join(["def sqr_n2(n: Nat, +x: Fq2) -> Fq2:", "  match n:", "    case 0n:", "      x",
                      "    case 1n+k:", "      Fq2{+a, +c} = x"] + ["    " + l for l in steps]
                     + [f"      sqr_n2(k, {res})"]) + "\n"


pow_t = re.search(r"^def pow_t\(\+x: B\.Fq\) -> B\.Fq:\n(.*?)\n\n", sq, re.S | re.M).group(1)
pow_t2 = ("def pow_t2(+x: Fq2) -> Fq2:\n"
          + pow_t.replace("B.sqr_n(", "sqr_n2(").replace("B.sqr(", "sqr2(").replace("B.mul(", "mul2(") + "\n")

out = f'''# GENERATED by lib/gen_fq2.py. Do not edit.
# Two-lane Fq arithmetic and Vesta point decompression: two independent inputs in lockstep, so
# their dependent chains overlap in the core. Each lane computes exactly what the one-lane
# function it is copied from computes (see gen_fq2.py).
import Base
import ../../../zcash/halo2/lib/words.bend as Wd
import ../../../crypto/field3/fq64.bend as B
import ../../../crypto/field3/intrinsics.bend as I
import ../../decomp/fq_sqrt.bend as SQ
import ../../decomp/vesta_dec.bend as VD

type Fq2 is Data:
  Fq2{{x: B.Fq, y: B.Fq}}

# (sqr_d x, sqr_d y)
{two_lane("sqr2", "sqr_d", "p: Fq2", ["  Fq2{+a, +c} = p"], {"a": "c", "v": "u"})}
# (mul a b, mul c d) for p = (a, c), q = (b, d)
{two_lane("mul2", "mul", "p: Fq2, q: Fq2", ["  Fq2{+a, +c} = p", "  Fq2{+b, +d} = q"], {"a": "c", "b": "d", "v": "u"})}
{sqr_n2_inline()}
# (pow_t x, pow_t y)
{pow_t2}
def root2_fin(p: Fq2, v: Fq2) -> Fq2:
  Fq2{{+x, +y}} = p
  Fq2{{+vx, +vy}} = v
  Fq2{{SQ.common(B.mul(x, vx), vx), SQ.common(B.mul(y, vy), vy)}}

# (SQ.root x, SQ.root y)
def root2(+p: Fq2) -> Fq2:
  root2_fin(p, pow_t2(p))

type D2 is Data:
  D2{{a: VD.Dec, b: VD.Dec}}

def dec2_fin(+x1: B.Fq, +s1: U32, +c1: U32, +r1: B.Fq, +x2: B.Fq, +s2: U32, +c2: U32, +r2: B.Fq, y: Fq2) -> D2:
  Fq2{{+y1, +y2}} = y
  D2{{VD.dec_ct_fin(x1, s1, c1, y1, SQ.is_root(y1, r1)), VD.dec_ct_fin(x2, s2, c2, y2, SQ.is_root(y2, r2))}}

def dec2_x(+x1: B.Fq, +s1: U32, +c1: U32, +x2: B.Fq, +s2: U32, +c2: U32) -> D2:
  +r1 = VD.rhs(x1)
  +r2 = VD.rhs(x2)
  dec2_fin(x1, s1, c1, r1, x2, s2, c2, r2, root2(Fq2{{r1, r2}}))

# (VD.decompress_ct w1, VD.decompress_ct w2)
def decompress2(+w1: Wd.W, +w2: Wd.W) -> D2:
  +xw1 = Wd.clear_top_bit(w1)
  +xw2 = Wd.clear_top_bit(w2)
  dec2_x(B.from_words(xw1), Wd.top_bit(w1), Bool.to_u32(Wd.is_lt(xw1, B.modulus())), B.from_words(xw2), Wd.top_bit(w2), Bool.to_u32(Wd.is_lt(xw2, B.modulus())))
'''
(here / "fq2.bend").write_text(out)
print("wrote lib/fq2.bend")
