#!/usr/bin/env python3
"""orchard_ba_{nu62,prenu62}.bend + bundle_ba_{nu62,prenu62}.bend: the older-circuit
verifiers (research/fast/pure/v32/orchard_dyn_*.bend, which differ from orchard_dyn.bend only in VK
constants) moved onto field3 fields and perf3's batch-affine MSM by the same edit perf3 made
for orchard_dyn.bend -> research/perf3/v64/orchard_ba.bend (imports + the final MSM call), so the
nu62 / prenu62 bundle sets exercise this directory's decompression too."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
V32 = HERE.parent.parent / "fast/pure/v32"

HDR_OLD = """import ../../../../zcash/halo2/lib/words.bend as Wd
import ../fp32.bend as Fp
import ../fq32.bend as Fq
import ../lib32/vesta.bend as V
import ../lib32/msm.bend as MSM
import ../lib32/msm_fast.bend as MF
"""
HDR_NEW = """import ../../../zcash/halo2/lib/words.bend as Wd
import ../../../crypto/field3/fp64.bend as Fp
import ../../../crypto/field3/fq64.bend as Fq
import ../../../crypto/field3/lib64/vesta.bend as V
import ../../../crypto/field3/lib64/msm.bend as MSM
import ../../../crypto/field3/lib64/msm_fast.bend as MF
import ../../perf3/lib_64/msm_ba.bend as BA
"""
MSM_OLD = re.compile(r"L\.bpt\(MF\.pip\(8, 0n, MF\.chunks\(0n, U32\.from_nat\(List\.length\(&2, V\.Pt, (t\d+)\)\), \1, (t\d+)\)\)\)")

for v in ("nu62", "prenu62"):
    s = (V32 / f"orchard_dyn_{v}.bend").read_text()
    assert s.count(HDR_OLD) == 1
    s = s.replace(HDR_OLD, HDR_NEW)
    s, n = MSM_OLD.subn(r"L.bpt(BA.msm9(9, \1, \2))", s)
    assert n == 1, n
    s = s.replace("# GENERATED by", f"# GENERATED by research/decomp/v64/gen_variants.py from research/fast/pure/v32/orchard_dyn_{v}.bend, originally by", 1)
    (HERE / f"orchard_ba_{v}.bend").write_text(s)
    b = (HERE / "bundle_ba.bend").read_text()
    assert b.count("import ./orchard_ba.bend as O") == 1
    (HERE / f"bundle_ba_{v}.bend").write_text(b.replace("import ./orchard_ba.bend as O", f"import ./orchard_ba_{v}.bend as O"))
    print("wrote", v)
