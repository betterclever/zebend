#!/usr/bin/env python3
"""Generate scan2's support modules.

kdf.bend: BLAKE2b-256 ("Zcash_OrchardKDF") and ChaCha20 keystream word 0, copied
          verbatim from gpu-scan's generated zcrypto.bend (they only use U32).
glv.bend: GLV split / endomorphism for Pallas on field3's 64-bit-limb fields, emitted
          by research/algo/lib/gen_glv.py with the import paths pointed at field3.
"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))

z = open(os.path.join(root, "research", "gpu-scan", "zcrypto.bend")).read().split("\n")
def find(prefix):
    for i, l in enumerate(z):
        if l.startswith(prefix):
            return i
    sys.exit(f"gen.py: {prefix!r} not found in zcrypto.bend")
u8w = find("type U8w is Data:")
v16 = find("type V16 is Data:")
rec = find("type Rec is Data:")
kdf = ["# GENERATED by research/scan2/gen.py from research/gpu-scan/zcrypto.bend. Do not edit.",
       "# BLAKE2b-256 KDF and ChaCha20 keystream word 0 on U32 words.", "import Base", ""]
kdf += z[u8w:u8w + 2] + [""] + z[v16:rec]
open(os.path.join(here, "kdf.bend"), "w").write("\n".join(kdf).rstrip() + "\n")

# Load gen_glv's definitions without running its top-level loop (which rewrites research/algo/'s files).
src = open(os.path.join(root, "research", "algo", "lib", "gen_glv.py")).read()
src = src[:src.index("\nhere = os.path.dirname")]
gen_glv = {}
exec(compile(src, "gen_glv.py", "exec"), gen_glv)
c = dict(gen_glv["CURVES"]["pallas"])
c.update(curve="../../crypto/field3/lib64/pallas.bend", base="../../crypto/field3/fp64.bend")
text = gen_glv["emit"]("pallas", c)
text = text.replace("import ../../halo2/lib/words.bend as Wd", "import ../../zcash/halo2/lib/words.bend as Wd")
text = text.replace("import ../../fast/intrinsics.bend as I", "import ../fast/intrinsics.bend as I")
assert "../../../" not in text, "unexpected relative import left in glv.bend"
open(os.path.join(here, "glv.bend"), "w").write(text)
print("wrote kdf.bend, glv.bend")
