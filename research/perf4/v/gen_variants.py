#!/usr/bin/env python3
"""orchard_ba_{nu62,prenu62}.bend + bundle_ba_{nu62,prenu62}.bend: the older-circuit single
verifiers, made from this directory's orchard_ba.bend by swapping in the constants that differ
between research/decomp/v64/orchard_ba.bend and its orchard_ba_{v}.bend (VK commitments and
circuit constants; the transcript shape is the same). Every swapped line must occur exactly once."""
import difflib
from pathlib import Path
HERE = Path(__file__).resolve().parent
DEC = HERE.parent.parent / "decomp/v64"
base = (DEC / "orchard_ba.bend").read_text().split("\n")
mine = (HERE / "orchard_ba.bend").read_text()
for v in ("nu62", "prenu62"):
    var = (DEC / f"orchard_ba_{v}.bend").read_text().split("\n")
    sm = difflib.SequenceMatcher(None, base, var, autojunk=False)
    s = mine; n = 0
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op == "equal": continue
        assert op == "replace" and i2 - i1 == j2 - j1, (op, i1, i2, j1, j2)
        for a, b in zip(base[i1:i2], var[j1:j2]):
            if a.startswith("#"): continue
            assert s.count(a + "\n") == 1, a[:80]
            s = s.replace(a + "\n", b + "\n"); n += 1
    # opt_gates.py folded K0 = 1 and K1 = 0 into the code: they must not differ per circuit
    for k, body in (("K0", "4294967293, 880307512, 3826848941, 2569811211, 4294967295, 4294967295, 4294967295, 1073741823"), ("K1", "0, 0, 0, 0, 0, 0, 0, 0")):
        assert f"def {k}() -> L.BF:\n  L.BF0{{Fp.Fp{{{body}}}}}" in s, k
    s = s.replace("# GENERATED by", f"# GENERATED by research/perf4/v/gen_variants.py ({v} constants) from orchard_ba.bend, originally by", 1)
    (HERE / f"orchard_ba_{v}.bend").write_text(s)
    b = (HERE / "bundle_ba.bend").read_text()
    assert b.count("import ./orchard_ba.bend as O") == 1
    (HERE / f"bundle_ba_{v}.bend").write_text(b.replace("import ./orchard_ba.bend as O", f"import ./orchard_ba_{v}.bend as O"))
    print("wrote", v, "lines swapped", n)
