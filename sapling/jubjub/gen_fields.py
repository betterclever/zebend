#!/usr/bin/env python3
"""Generates the two Jubjub fields with field3's 4 x 64-bit-limb generator (U32.mac64):

  fr.bend  type Fr: GF(r_BLS), r = BLS12-381's scalar field = Jubjub's BASE field (255 bits).
           r - 1 = 2^32 * t (2-adicity 32, like Pasta) and 5 is a non-residue, so field3's
           Tonelli-Shanks code applies unchanged.
  fs.bend  type Fs: GF(r_J), Jubjub's prime-order subgroup scalar field (252 bits). Only
           mul/add/sub/from_wide/to_words are used (RedJubjub challenges and batch weights);
           its generated sqrt is meaningless (2-adicity 1) and must not be used.

Everything is generic in the modulus except the header comment (Pasta names) and the
import paths, which are patched below.

  python3 gen_fields.py
"""
import importlib.util
import pathlib
import re

here = pathlib.Path(__file__).resolve().parent
f3 = here.parent.parent / "field3"
spec = importlib.util.spec_from_file_location("gen_field64", f3 / "gen_field64.py")
g64 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g64)
g3, g16 = g64.g3, g64.g3.g16

R_BLS = 0x73EDA753299D7D483339D80809A1D80553BDA402FFFE5BFEFFFFFFFF00000001
R_J = 0x0E7DB4EA6533AFA906673B0101343B00A6682093CCC81082D0970E5ED6F72CB7

assert pow(5, (R_BLS - 1) // 2, R_BLS) == R_BLS - 1  # 5 is a non-residue
assert (R_BLS - 1) % (1 << 32) == 0 and ((R_BLS - 1) >> 32) % 2 == 1


def gen(name, m, desc, path):
    # The Pasta generators key their header comment by modulus; point them at m.
    g3.P = g16.P = m
    src = g64.Field64(name, m).module()
    src = re.sub(r"^# GENERATED by .*$", "# GENERATED by sapling/jubjub/gen_fields.py (via field3/gen_field64.py). Do not edit.", src, count=1, flags=re.M)
    src = re.sub(r"^# GF\(.*$", f"# GF({desc}) = {hex(m)}", src, count=1, flags=re.M)
    src = src.replace("import ../halo2/lib/words.bend as Wd", "import ../../halo2/lib/words.bend as Wd")
    src = src.replace("import ./intrinsics.bend as I", "import ../../field3/intrinsics.bend as I")
    assert "../../halo2/lib/words.bend" in src and "../../field3/intrinsics.bend" in src
    (here / path).write_text(src)


gen("Fr", R_BLS, "r: bls12_381::Scalar = Jubjub base field", "fr.bend")
gen("Fs", R_J, "r_J: jubjub::Fr = Jubjub scalar field; sqrt NOT valid (2-adicity 1)", "fs.bend")
print("wrote fr.bend fs.bend")
