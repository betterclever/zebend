#!/usr/bin/env python3
"""Expand AC macros in a .src file into calls of ac.bend's decision procedure.

    AC[[ lhs |=| rhs ]]   ->   A.ac([atoms...], e1, e2, {==})

lhs and rhs are Bend Nat expressions. Nested Nat.add(x, y) calls and `kn+x` prefixes
become sum nodes; every other subterm is an atom (atoms are compared as text, so the
same subterm must be written the same way on both sides). The checker then decides
the equation by sorting the atom indices, and ac.bend's soundness lemma turns that
into the equation itself.

Usage: acgen.py IN.src OUT.bend
"""
import re
import sys


def split_top(s):
    out, depth, cur = [], 0, []
    for ch in s:
        if ch in "([{<":
            depth += 1
        elif ch in ")]}>":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    out.append("".join(cur).strip())
    return out


def closes_at_end(s, start):
    depth = 0
    for i in range(start, len(s)):
        if s[i] in "([{":
            depth += 1
        elif s[i] in ")]}":
            depth -= 1
            if depth == 0:
                return i == len(s) - 1
    return False


def parse(s, atoms):
    s = s.strip()
    m = re.match(r"^(\d+)n\+(.*)$", s, re.S)
    if m and int(m.group(1)) > 0:
        k = int(m.group(1))
        node = parse(m.group(2), atoms)
        for _ in range(k):
            node = ("P", ("V", atom("1n", atoms)), node)
        return node
    if s.startswith("Nat.add(") and closes_at_end(s, len("Nat.add")):
        a, b = split_top(s[len("Nat.add("):-1])
        return ("P", parse(a, atoms), parse(b, atoms))
    return ("V", atom(s, atoms))


def atom(s, atoms):
    key = re.sub(r"\s+", " ", s)
    if key not in atoms:
        atoms[key] = len(atoms)
    return atoms[key]


def show(e):
    if e[0] == "V":
        return "A.AV{%dn}" % e[1]
    return "A.AP{%s, %s}" % (show(e[1]), show(e[2]))


def expand(body):
    lhs, rhs = body.split("|=|")
    atoms = {}
    e1 = parse(lhs, atoms)
    e2 = parse(rhs, atoms)
    env = ", ".join(sorted(atoms, key=atoms.get))
    return "A.ac([%s], %s, %s, {==})" % (env, show(e1), show(e2))


def main():
    src = open(sys.argv[1]).read()
    out = re.sub(r"AC\[\[(.*?)\]\]", lambda m: expand(m.group(1)), src, flags=re.S)
    hdr = "# GENERATED by acgen.py from %s. Do not edit.\n" % sys.argv[1].split("/")[-1]
    open(sys.argv[2], "w").write(hdr + out)


if __name__ == "__main__":
    main()
