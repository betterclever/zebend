"""Writes certs.bend: the ring identities lemmas.bend needs, with their certificates.

Run from this directory: python3 gen.py (needs sympy). Nothing here is trusted: each
certificate is re-checked by ring/cert.bend's cert_ok2 when Bend checks PROOF.bend.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ring'))
from certgen import V, C, mul, emit, HEADER  # noqa: E402

ONE = C(1)
OBLIGATIONS = [
    # env [x, inv, a2, a]: a = a2 x and a inv = 1 give x (inv a2) = 1 and a2 (inv x) = 1
    ('r1', 4, mul(V(0), mul(V(1), V(2))), ONE, [(V(3), mul(V(2), V(0))), (mul(V(3), V(1)), ONE)], [3, 2, 1, 0]),
    ('r2', 4, mul(V(2), mul(V(1), V(0))), ONE, [(V(3), mul(V(2), V(0))), (mul(V(3), V(1)), ONE)], [3, 2, 1, 0]),
    # env [acc, h, ia, ih]: (acc h)(ia ih) = (acc ia)(h ih)
    ('r4', 4, mul(mul(V(0), V(1)), mul(V(2), V(3))), mul(mul(V(0), V(2)), mul(V(1), V(3))), [], [0, 1, 2, 3]),
    # env [x, y, fx]: x y = 1 and x fx = 1 give y = fx
    ('r5', 3, V(1), V(2), [(mul(V(0), V(1)), ONE), (mul(V(0), V(2)), ONE)], [1, 2, 0]),
]


def main():
    parts = [HEADER % {'ring': '../ring'}, '# GENERATED by gen.py. Do not edit.\n']
    for name, n, t1, t2, rels, order in OBLIGATIONS:
        text, size, ncp = emit(name, n, t1, t2, rels, order)
        parts.append('# --- %s: %d monomials, %d checkpoints\n' % (name, size, ncp))
        parts.append(text)
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'certs.bend'), 'w') as f:
        f.write('\n'.join(parts))


if __name__ == '__main__':
    main()
