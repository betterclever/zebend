"""Emit gates_model.bend for proofs/orchard_mul from zcash/halo2/gen/orchard_cs.bend.

The four base-constancy constraints of the incomplete-addition loop of variable-base
scalar multiplication (halo2_gadgets ecc/chip/mul/incomplete.rs, gate "q_mul_2 == 1 checks"):
  gate_8_0  hi half, "x_p_check":  x_p(cur) - x_p(next)
  gate_8_1  hi half, "y_p_check":  y_p(cur) - y_p(next)
  gate_11_0 lo half, "x_p_check"
  gate_11_1 lo half, "y_p_check"
Gate / constraint names: proofs/orchard/names/names.txt. Each is emitted exactly as
../orchard/gates.py emits the other gates (compressed selector factor -> `sel`, Montgomery
constants decoded), with its two advice queries as the parameters `cur`, `next`. The script
checks that the queries are (column 0 | 1, rotation 0) and (same column, rotation +1), the
x_p / y_p columns the extracted layout anchors (zcash/halo2/constraints).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../orchard"))
import gates as G

SRC = open(os.path.join(HERE, "..", "..", "zcash", "halo2", "gen", "orchard_cs.bend")).read()
import re
cols = [int(x) for x in re.search(r"def ADVICE_QUERY_COLUMN\(\) -> \+List<U32>:\n  \[([\d, ]+)\]", SRC).group(1).split(",")]
rots = [int(x) for x in re.search(r"def ADVICE_QUERY_ROTATION\(\) -> \+List<U32>:\n  \[([\d, ]+)\]", SRC).group(1).split(",")]

gates = G.parse()
out = ["import Base", "import ../orchard/fieldmodel.bend as F", "",
       "# GENERATED by gen.py from zcash/halo2/gen/orchard_cs.bend. Do not edit.",
       "# The base-constancy constraints of variable-base scalar mul's incomplete-addition loop,",
       "# selector factor as `sel`, over p = 1 + pp; cur / next are x_p (or y_p) on rows r, r+1.", ""]
for name, col in [("gate_8_0", 0), ("gate_8_1", 1), ("gate_11_0", 0), ("gate_11_1", 1)]:
    e = gates[name]
    assert e[0] == "fmul"
    body = e[2]
    vs = sorted(G.vars_of(body, set()), key=lambda v: v[1])
    assert [v[0] for v in vs] == ["a", "a"], name
    (_, q0), (_, q1) = vs
    assert (cols[q0], rots[q0]) == (col, 0) and (cols[q1], rots[q1]) == (col, 1), (name, cols[q0], rots[q0], cols[q1], rots[q1])
    expr = f"fmul(1n+pp, sel, {G.bend(body)})"
    expr = re.sub(rf"\ba{q0}\b", "cur", expr)
    expr = re.sub(rf"\ba{q1}\b", "next", expr)
    expr = expr.replace("fadd(", "F.fadd(").replace("fsub(", "F.fsub(").replace("fmul(", "F.fmul(")
    out += [f"# {name}: advice query {q0} = (column {col}, rotation 0), query {q1} = (column {col}, rotation +1)",
            f"def {name}(+pp: Nat, +sel: Nat, +cur: Nat, +next: Nat) -> Nat:", f"  {expr}", ""]
open(os.path.join(HERE, "gates_model.bend"), "w").write("\n".join(out))
print("wrote gates_model.bend (4 gates)")
