#!/usr/bin/env python3
"""Generates bit-level round-trip proofs for node/p2p's little-endian byte codecs.

Bend's checker normalizes B.get_le32(B.le32(x)) for a symbolic 32-bit x (32 Bool
variables) to a word whose bit i is an expression in b_i alone (e.g.
Bool.or(Bool.and(b8, False{}), Bool.and(b8, True{}))). We ask Bend for that normal
form (`?g`), then emit, per position, a two-case lemma `E_i(b) == b`, and chain them
with congruence. The proof is linear in the word size and checked by Bend like any
other proof; this script only writes it.  Usage: gen_bits.py  (writes bits.bend)
"""
import re, subprocess

BEND = "~/.bend/bin/bend"
N = 32

def word(xs):
    w = "WNil{}"
    for x in reversed(xs):
        w = f"WCon{{{x}, {w}}}"
    return w

def run_probe(name, lhs, bits):
    params = ", ".join(f"+b{i}: Bool" for i in range(len(bits)) if bits[i] is None)
    xs = [f"b{i}" if bits[i] is None else bits[i] for i in range(N)]
    src = f"""import Base
import ../../node/p2p/bytes.bend as B

def probe({params}) -> {{{lhs.replace("X", "U32{" + word(xs) + "}")} == U32{{{word(xs)}}} : U32}}:
  ?g
"""
    open("probe.bend", "w").write(src)
    out = subprocess.run(["zsh", "-lc", f"export BEND_NO_TELEMETRY=1; {BEND} probe.bend --check-only"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True).stdout
    m = re.search(r"- expected : \{(.*) : U32\}\n", out)
    assert m, out[:2000]
    eq = m.group(1)
    assert eq.startswith("U32{"), eq[:200]
    return parse_word(eq[4:])

def split_args(s, i):
    """Parse 'WCon{E, REST}' starting at s[i]; return (E, index of REST)."""
    assert s.startswith("WCon{", i), s[i:i + 40]
    j = i + 5; depth = 0
    while True:
        c = s[j]
        if c in "({": depth += 1
        elif c in ")}": depth -= 1
        elif c == "," and depth == 0:
            return s[i + 5:j], j + 2
        j += 1

def parse_word(s):
    es, i = [], 0
    while not s.startswith("WNil{}", i):
        e, i = split_args(s, i)
        es.append(e)
    assert len(es) == N, len(es)
    return es

def gen(prefix, lhs, bits):
    es = run_probe(prefix, lhs, bits)
    free = [i for i in range(N) if bits[i] is None]
    xs = [f"b{i}" if bits[i] is None else bits[i] for i in range(N)]
    out = []
    # per-position lemmas
    for i in range(N):
        e = es[i]
        if bits[i] is None:
            gen_e = re.sub(rf"\bb{i}\b", "b", e)
            assert not re.search(r"\bb\d+\b", gen_e), (i, e)
            out.append(f"def {prefix}.bit{i}(+b: Bool) -> {{{gen_e} == b : Bool}}:\n  match b:\n    case True{{}}:\n      {{==}}\n    case False{{}}:\n      {{==}}\n")
        else:
            assert not re.search(r"\bb\d+\b", e), (i, e)
    # congruence chain, innermost (bit 31) first
    def tail(lst, k):
        return word(lst[k:])
    chain = "{==}"
    for i in reversed(range(N)):
        rest_len = N - 1 - i
        head = f"{prefix}.bit{i}(b{i})" if bits[i] is None else "{==}"
        chain = (f"W.wcon({rest_len}n, {es[i]}, {xs[i]}, {tail(es, i + 1)}, {tail(xs, i + 1)}, {head}, {chain})")
    params = ", ".join(f"+b{i}: Bool" for i in free)
    goal_lhs = lhs.replace("X", "U32{" + word(xs) + "}")
    out.append(f"""def {prefix}.word({params}) -> {{{goal_lhs} == U32{{{word(xs)}}} : U32}}:
  Equal.cong(Word(32n), U32, W.u32, {word(es)}, {word(xs)},
    {chain})
""")
    return "\n".join(out)

hdr = """# GENERATED by gen_bits.py: bit-level round-trip lemmas for node/p2p's byte codecs.
import Base
import ../../node/p2p/bytes.bend as B
import ./wordlemmas.bend as W

"""
le32 = gen("le32", "B.get_le32(B.le32(X))", [None] * N)
le16 = gen("le16", "B.get_le16(B.le16(X))", [None] * 16 + ["False{}"] * 16)
open("bits.bend", "w").write(hdr + le32 + "\n" + le16)
print("wrote bits.bend")

# ---- x < 65536  ==>  bits 16..31 are zero: a linear case split on b31 .. b16 ----
def hi_chain():
    out = []
    for K in range(16, 32):
        bits = [f"b{i}" for i in range(K + 1)] + ["False{}"] * (31 - K)
        w = word(bits)
        params = ", ".join(f"+b{i}: Bool" for i in range(K + 1))
        goal = f"{{B.get_le16(B.le16(U32{{{w}}})) == U32{{{w}}} : U32}}"
        hyp = f"{{U32.is_lt(U32{{{w}}}, 65536) == True{{}} : Bool}}"
        tw = word([f"b{i}" for i in range(K)] + ["True{}"] + ["False{}"] * (31 - K))
        tgoal = f"{{B.get_le16(B.le16(U32{{{tw}}})) == U32{{{tw}}} : U32}}"
        if K > 16:
            bad = "h"
            nxt = f"le16.hi{K - 1}({', '.join(f'b{i}' for i in range(K))}, h)"
        else:
            w16 = word([f"b{i}" for i in range(16)])
            mid = f"Cmp.is_lt(Word.cmp(16n, {w16}, Word.zero(16n)))"
            bad = f"Equal.trans(Bool, False{{}}, {mid}, True{{}}, Equal.sym(Bool, {mid}, False{{}}, W.cmp_zero_nlt(16n, {w16})), h)"
            nxt = f"le16.word({', '.join(f'b{i}' for i in range(16))})"
        out.append(f"""def le16.hi{K}({params}) -> {hyp} -> {goal}:
  match b{K}:
    case True{{}}:
      h => W.absurd({tgoal}, W.false_not_true({bad}))
    case False{{}}:
      h => {nxt}
""")
    return "\n".join(out)

def pattern():
    p = "WNil{}"
    for i in reversed(range(N)):
        p = f"WCon{{+b{i}, {p}}}"
    return f"U32{{{p}}}"

allb = ", ".join(f"b{i}" for i in range(N))
tops = f"""
# For every U32 x: decoding the 4-byte little-endian encoding gives x back.
def le32.rt(x: U32) -> {{B.get_le32(B.le32(x)) == x : U32}}:
  match x:
    case {pattern()}:
      le32.word({allb})

# For every U32 x < 65536: decoding the 2-byte little-endian encoding gives x back.
def le16.rt(x: U32) -> {{U32.is_lt(x, 65536) == True{{}} : Bool}} -> {{B.get_le16(B.le16(x)) == x : U32}}:
  match x:
    case {pattern()}:
      h => le16.hi31({allb}, h)
"""
with open("bits.bend", "a") as f:
    f.write("\n" + hi_chain() + tops)
print("appended hi chain + top lemmas")
