#!/usr/bin/env python3
"""Generates limbs.bend: proofs that halo2/lib's 16-bit limb split is lossless.

Bend's U32 is a 32-bit inductive bit vector, so a proof can take a U32 apart into
its 32 bits; every shift/mask then computes structurally and each bit is closed
with a two-case Bool lemma. Writing the 32 rewrites by hand would be error-prone,
so this script emits them."""
N = 32
bits = [f"b{i}" for i in range(N)]

def word(xs):
    s = "WNil{}"
    for x in reversed(xs):
        s = f"WCon{{{x}, {s}}}"
    return s

A = f"U32{{{word(bits)}}}"
LHS = f"U32.or(U32.and({A}, 65535), U32.shln(U32.shrn({A}, 16n), 16n))"
lo = lambda b: f"Bool.or(Bool.and({b}, True{{}}), False{{}})"
hi = lambda b: f"Bool.or(Bool.and({b}, False{{}}), {b})"
form = lambda i: lo(bits[i]) if i < 16 else hi(bits[i])

out = ['''import Base
import ../../halo2/lib/words.bend as Wd
import ../../halo2/lib/fp.bend as Fp

# GENERATED by gen_limbs.py.

law bit_lo:
  for x: Bool
  {Bool.or(Bool.and(x, True{}), False{}) == x : Bool}

def bit_lo(x):
  match x:
    case False{}:
      {==}
    case True{}:
      {==}

law bit_hi:
  for x: Bool
  {Bool.or(Bool.and(x, False{}), x) == x : Bool}

def bit_hi(x):
  match x:
    case False{}:
      {==}
    case True{}:
      {==}

# Splitting a U32 into 16-bit halves and joining them back gives the same U32.
law split32:
  for a: U32
  {U32.or(U32.and(a, 65535), U32.shln(U32.shrn(a, 16n), 16n)) == a : U32}

def split32(a):
  match a:
    case U32{w0}:''']
ind = "      "
for i in range(N):
    out.append(f"{ind}match w{i}:")
    out.append(f"{ind}  case WCon{{{bits[i]}, w{i+1}}}:")
    ind += "    "
out.append(f"{ind}match w{N}:")
out.append(f"{ind}  case WNil{{}}:")
ind += "    "
for i in range(N):
    rhs = [form(j) for j in range(i)] + ["_"] + bits[i+1:]
    lem = "bit_lo" if i < 16 else "bit_hi"
    out.append(f"{ind}%{lem}({bits[i]}) : {{{LHS} == U32{{{word(rhs)}}} : U32}}")
out.append(f"{ind}{{==}}")

W = ["a", "b", "c", "d", "e", "f", "g", "h"]
split = lambda v: f"U32.or(U32.and({v}, 65535), U32.shln(U32.shrn({v}, 16n), 16n))"
out.append('''
# The field's limb layer is lossless: for every 256-bit input w (8 little-endian
# words), Fp.raw splits it into 16 limbs and Fp.unraw reassembles exactly w.
law raw_roundtrip:
  for w: Wd.W
  {Fp.unraw(Fp.raw(w)) == w : Wd.W}

def raw_roundtrip(w):
  match w:
    case Wd.W{a, b, c, d, e, f, g, h}:''')
for i, v in enumerate(W):
    rhs = [split(W[j]) for j in range(i)] + ["_"] + W[i+1:]
    out.append(f"      %split32({v}) : {{Fp.unraw(Fp.raw(Wd.W{{{', '.join(W)}}})) == Wd.W{{{', '.join(rhs)}}} : Wd.W}}")
out.append("      {==}")
open("limbs.bend", "w").write("\n".join(out) + "\n")
print("wrote limbs.bend")
