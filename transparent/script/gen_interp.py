# NOP1, NOP3..NOP10 fall through to the end of the chain.
LAST = "o_nop(stk, alt, ops, env)"
SIG = "(+b: U32, +mn: Bool, +stk: List<&2, +List<U32>>, +alt: List<&2, +List<U32>>, +ops: U32, +env: C.Env) -> C.R3"
out = []
n = len(OPS)
for i in reversed(range(n)):
    code, expr = OPS[i]
    nxt = LAST if i == n - 1 else f"ex_{i+1}(U32.is_eq(b, {OPS[i+1][0]}), b, mn, stk, alt, ops, env)"
    out.append(f"def ex_{i}(hit: Bool, {SIG[1:]}:\n  match hit:\n    case True{{}}:\n      {expr}\n    case False{{}}:\n      {nxt}\n")

chain = "\n".join(out)
chain += f"\n# An operation (not a push or control opcode) on an executing branch.\ndef exec_op{SIG}:\n  ex_0(U32.is_eq(b, {OPS[0][0]}), b, mn, stk, alt, ops, env)\n"
text = (HERE / "interp_head.bend").read_text() + "\n# ---- generated by gen_interp.py: opcode dispatch\n\n" + chain + "\n" + (HERE / "interp_tail.bend").read_text()
(HERE / "interp.bend").write_text(text)
print("wrote interp.bend")
