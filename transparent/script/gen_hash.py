def rotl(x, n):
    return f"(({x} << {n}n) .|. ({x} >> {32 - n}n) : U32)"


def f(i, x, y, z):
    return [f"({x} .^. {y} .^. {z} : U32)",
            f"(({x} .&. {y}) .|. (U32.not({x}) .&. {z}) : U32)",
            f"(({x} .|. U32.not({y})) .^. {z} : U32)",
            f"(({x} .&. {z}) .|. ({y} .&. U32.not({z})) : U32)",
            f"({x} .^. ({y} .|. U32.not({z})) : U32)"][i]


class Emit:
    def __init__(self):
        self.lines, self.n = [], 0

    def let(self, expr):
        self.n += 1
        v = f"v{self.n}"
        self.lines.append(f"  +{v} = {expr}")
        return v


def rmd_line(right):
    e = Emit()
    e.lines.append("  RS{+h0, +h1, +h2, +h3, +h4} = h")
    e.lines.append("  M16{" + ", ".join(f"+x{i}" for i in range(16)) + "} = m")
    a, b, c, d, ee = "h0", "h1", "h2", "h3", "h4"
    R, S, K = (R_R, S_R, K_R) if right else (R_L, S_L, K_L)
    for j in range(80):
        g = j // 16
        fi = 4 - g if right else g
        s = e.let(f"({a} + {f(fi, b, c, d)} + x{R[j]} + {K[g]} : U32)")
        t = e.let(f"({rotl(s, S[j])} + {ee} : U32)")
        a, ee, d, c, b = ee, d, e.let(rotl(c, 10)), b, t
    name = "rmd_right" if right else "rmd_left"
    return (f"def {name}(+h: RS, +m: M16) -> RS:\n" + "\n".join(e.lines) + f"\n  RS{{{a}, {b}, {c}, {d}, {ee}}}\n")


def sha1_compress():
    e = Emit()
    e.lines.append("  RS{+h0, +h1, +h2, +h3, +h4} = h")
    e.lines.append("  M16{" + ", ".join(f"+x{i}" for i in range(16)) + "} = m")
    w = [f"x{i}" for i in range(16)]
    for t in range(16, 80):
        w.append(e.let(rotl(f"({w[t-3]} .^. {w[t-8]} .^. {w[t-14]} .^. {w[t-16]} : U32)", 1)))
    a, b, c, d, ee = "h0", "h1", "h2", "h3", "h4"
    for t in range(80):
        if t < 20:
            fv, k = f"(({b} .&. {c}) .|. (U32.not({b}) .&. {d}) : U32)", 0x5A827999
        elif t < 40:
            fv, k = f"({b} .^. {c} .^. {d} : U32)", 0x6ED9EBA1
        elif t < 60:
            fv, k = f"(({b} .&. {c}) .|. ({b} .&. {d}) .|. ({c} .&. {d}) : U32)", 0x8F1BBCDC
        else:
            fv, k = f"({b} .^. {c} .^. {d} : U32)", 0xCA62C1D6
        tmp = e.let(f"({rotl(a, 5)} + {fv} + {ee} + {k} + {w[t]} : U32)")
        ee, d, c, b, a = d, c, e.let(rotl(b, 30)), a, tmp
    return ("def sha1_compress(+h: RS, +m: M16) -> RS:\n" + "\n".join(e.lines) +
            f"\n  RS{{(h0 + {a} : U32), (h1 + {b} : U32), (h2 + {c} : U32), (h3 + {d} : U32), (h4 + {ee} : U32)}}\n")


