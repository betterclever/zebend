#!/usr/bin/env python3
"""Speed round 2: single-pass message-block readers for the list-based hashes.

  python3 gen_hash2.py   # writes ../sighash2/sha256.bend and ../script2/rmd_sha1.bend

Round 1's SHA-256 (node/block/sha256.bend) and RIPEMD-160 / SHA-1 (script/rmd_sha1.bend) read
word i of a 64-byte block with its own drop from the block's head (16 walks, 480 cells per
block on top of the 64 read) and then dropped 64 bytes again to reach the next block. Walking a
shared byte list costs refcount traffic per cell, so the copies here read the 16 words in one
pass and carry the rest of the list to the next block. The compression functions, padding and
outputs are unchanged (text-identical)."""
import pathlib
T = pathlib.Path(__file__).resolve().parents[1]

# ---- SHA-256
s = (T / "../node/block/sha256.bend").read_text()
s = s.replace("import ./bytes.bend as B", "import ../../node/block/bytes.bend as B")
s = s.replace("# SHA-256 (FIPS 180-4) over byte lists,", "# GENERATED by transparent/secp2/gen_hash2.py from node/block/sha256.bend (single-pass block\n# reader, see there). SHA-256 (FIPS 180-4) over byte lists,", 1)
old_bw = s[s.index("def be_at("):s.index("def be32(")]
new_bw = '''# A big-endian word and the rest of the list (fewer than 4 bytes: 0 and Nil).
type Rw is Data:
  Rw{w: U32, rest: +List<U32>}

def rdw(xs: +List<U32>) -> Rw:
  match xs:
    case Con{a, Con{b, Con{c, Con{d, t}}}}:
      Rw{((a << 24n) .|. (b << 16n) .|. (c << 8n) .|. d : U32), t}
    case _:
      Rw{0, Nil{}}

def rw_w(r: Rw) -> U32:
  Rw{w, _} = r
  w

def rw_r(r: Rw) -> +List<U32>:
  Rw{_, t} = r
  t

# The next 64-byte block's words, read in one pass, and the bytes after it.
type Blk is Data:
  Blk{w: W16, rest: +List<U32>}

def blk(+xs: +List<U32>) -> Blk:
''' + "".join(f"  +r{i} = rdw({'xs' if i == 0 else f'rw_r(r{i - 1})'})\n" for i in range(16)) + \
'''  Blk{W16{''' + ", ".join(f"rw_w(r{i})" for i in range(16)) + '''}, rw_r(r15)}

# n blocks; b is the next block, read ahead so the recursion stays direct.
def blocks(n: Nat, b: Blk, +st: S8) -> S8:
  match n:
    case 0n:
      st
    case 1n+p:
      Blk{+w, +rest} = b
      blocks(p, blk(rest), add8(st, rounds(ks(), st, w)))

'''
s = s.replace(old_bw, new_bw)
s = s.replace("  digest(blocks(U32.to_nat(nblk), pad(xs, len), iv()))", "  digest(blocks(U32.to_nat(nblk), blk(pad(xs, len)), iv()))")
(T / "sighash2/sha256.bend").write_text(s)

# ---- RIPEMD-160 / SHA-1
r = (T / "script/rmd_sha1.bend").read_text()
a0, a1 = r.index("def m16("), r.index("def le4(")
r = r[:a0] + '''# A word (little-endian if le) and the rest of the list (fewer than 4 bytes: 0 and Nil).
type Rw is Data:
  Rw{w: U32, rest: +List<U32>}

def rdw(+le: Bool, xs: +List<U32>) -> Rw:
  match xs:
    case Con{+a, Con{+b, Con{+c, Con{+d, t}}}}:
      Rw{Bool.pick(U32, le, (a .|. (b << 8n) .|. (c << 16n) .|. (d << 24n) : U32), ((a << 24n) .|. (b << 16n) .|. (c << 8n) .|. d : U32)), t}
    case _:
      Rw{0, Nil{}}

def rw_w(r: Rw) -> U32:
  Rw{w, _} = r
  w

def rw_r(r: Rw) -> +List<U32>:
  Rw{_, t} = r
  t

type Blk is Data:
  Blk{m: M16, rest: +List<U32>}

# The next 64-byte block's words, read in one pass, and the bytes after it.
def blk(+le: Bool, +xs: +List<U32>) -> Blk:
''' + "".join(f"  +r{i} = rdw(le, {'xs' if i == 0 else f'rw_r(r{i - 1})'})\n" for i in range(16)) + \
'''  Blk{M16{''' + ", ".join(f"rw_w(r{i})" for i in range(16)) + '''}, rw_r(r15)}

''' + r[a1:]
b0, b1 = r.index("def comp("), r.index("def rmd_iv(")
r = r[:b0] + '''def comp(rmd: Bool, +h: RS, +m: M16) -> RS:
  match rmd:
    case True{}:
      rmd_compress(h, m)
    case False{}:
      sha1_compress(h, m)

# n blocks; b is the next block, read ahead so the recursion stays direct.
def blocks(n: Nat, +rmd: Bool, b: Blk, +h: RS) -> RS:
  match n:
    case 0n:
      h
    case 1n+p:
      Blk{+m, +rest} = b
      blocks(p, rmd, blk(rmd, rest), comp(rmd, h, m))

''' + r[b1:]
r = r.replace("True{}, pad(True{}, xs, len), rmd_iv()))", "True{}, blk(True{}, pad(True{}, xs, len)), rmd_iv()))")
r = r.replace("False{}, pad(False{}, xs, len), rmd_iv()))", "False{}, blk(False{}, pad(False{}, xs, len)), rmd_iv()))")
r = r.replace("# GENERATED by gen_hash.py", "# GENERATED by script/gen_hash.py, then transparent/secp2/gen_hash2.py (single-pass block reader)", 1)
(T / "script2/rmd_sha1.bend").write_text(r)
print("wrote sighash2/sha256.bend script2/rmd_sha1.bend")
