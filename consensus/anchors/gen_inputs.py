#!/usr/bin/env python3
"""Inputs for anchors_main.bend: the window of mainnet Ironwood leaves to replay block by
block, the anchors to check (from node/tx's real mainnet transactions), plus two tampered
cases. Also writes the Rust oracle's root history for the window, for diffing."""
import re, struct, pathlib
HERE = pathlib.Path(__file__).parent
ROOT = HERE.parent.parent
START = 3_527_600                                   # first block replayed in Bend
hist = [l.split() for l in open(HERE.parent / "oracle/out/iw_hist.txt")]
n0 = max(int(s) for h, s, r in hist if int(h) < START)
leaves = (ROOT / "node/state/oracle/out/leaves.bin").read_bytes()
rec = 68
heights = [struct.unpack_from("<I", leaves, i * rec)[0] for i in range(len(leaves) // rec)]
assert all(h < START for h in heights[:n0]) and heights[n0] >= START
(HERE / "window_heights.bin").write_bytes(b"".join(struct.pack("<I", h) for h in heights[n0:]))

def w(hexs):
    b = bytes.fromhex(hexs)
    return "Wd.W{" + ", ".join(str(struct.unpack_from("<I", b, 4 * i)[0]) for i in range(8)) + "}"

txs = []
for i in range(29):
    t = (ROOT / f"node/tx/mainnet/tx_{i}.txt").read_text()
    m = re.search(r"^ironwood\.anchor (\w+)", t, re.M)
    if m:
        txs.append((f"tx_{i}", int(re.search(r"^height (\d+)", t, re.M).group(1)), m.group(1)))
# Tampered: a random anchor, and a real root used in its own block (the rule needs an earlier block).
txs.append(("tamper_random_anchor", 3528100, "11" * 32))
same_block = next(r for h, s, r in hist if h == "3528073")
txs.append(("tamper_same_block_anchor", 3528073, same_block))

lines = ["# GENERATED by gen_inputs.py.", "import Base", "import ../../halo2/lib/words.bend as Wd", "",
         "type Tx is Data:", "  Tx{name: String, height: Nat, anchor: Wd.W}", "",
         f"def n0() -> U32:\n  {n0}\n", f"def leaf_count() -> U32:\n  {len(heights)}\n",
         "def activation_minus_1() -> Nat:\n  U32.to_nat(3428142)\n",
         "def txs() -> +List<Tx>:", "  [" + ", ".join(f'Tx{{"{n}", U32.to_nat({h}), {w(a)}}}' for n, h, a in txs) + "]", ""]
(HERE / "inputs.bend").write_text("\n".join(lines))
with open(HERE / "expected_window.txt", "w") as f:
    f.write(f"{3428142} {hist[0][2]}\n")
    for h, s, r in hist[1:]:
        if int(h) >= START:
            f.write(f"{h} {r}\n")
print(f"n0 {n0}, window leaves {len(heights) - n0}, txs {len(txs)}")
