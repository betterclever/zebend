#!/usr/bin/env python3
"""Inputs for the Bend issuance checker: funding-stream / founders' reward recipient
scripts (decoded from the addresses in ZIP 214 and zcashd's chainparams) and the coinbase
outputs of the sampled mainnet blocks (zcash/consensus/oracle `coinbase`)."""
import hashlib, pathlib, re
HERE = pathlib.Path(__file__).parent
ZIPS = pathlib.Path("/tmp/claude-501/-home-betterclever-projects-zecathon/770047ba-eee6-4f64-a49f-300605289ced/scratchpad/zips")
A = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"

def b58(s):
    n = 0
    for c in s:
        n = n * 58 + A.index(c)
    raw = n.to_bytes(26, "big")
    body, chk = raw[:-4], raw[-4:]
    assert hashlib.sha256(hashlib.sha256(body).digest()).digest()[:4] == chk, s
    return body

def script(addr):
    b = b58(addr)
    pre, h = b[:2], b[2:]
    if pre == bytes.fromhex("1cbd"):   # t3: P2SH
        return "a914" + h.hex() + "87"
    if pre == bytes.fromhex("1cb8"):   # t1: P2PKH
        return "76a914" + h.hex() + "88ac"
    raise ValueError(addr)

z214 = (ZIPS / "zip-0214.rst").read_text()
bp = re.findall(r'"(t3\w+)"', z214[z214.index("FS_ZIP214_BP.AddressList[0..47]"):z214.index("FS_ZIP214_ZF.AddressList[0..47]")])
assert len(bp) == 48
zf = "t3dvVE3SQEi7kqNzwrfNePxZ1d4hUyztBA1"
mg = "t3XyYW8yBFRuMnfvm5KLGFbEVz25kckZXym"
zcg = "t3cFfPt1Bcvgez9ZbMBFWeZsskxTkPzGCow"
disb = "t3ev37Q2uL1sfTsiJQJiWJoFzQpDhmnUwYo"
cp = (ZIPS / "chainparams.cpp").read_text()
blk = cp[cp.index("vFoundersRewardAddress = {"):]
fr = re.findall(r'"(t3\w+)"', blk[:blk.index("};")])
assert len(fr) == 48, len(fr)

def nat(v):
    hi, lo = divmod(v, 1 << 32)
    return f"P.big({hi}, {lo})" if hi else f"U32.to_nat({lo})"

def slist(xs):
    return "[" + ", ".join(f'"{script(a)}"' for a in xs) + "]"

blocks = {}
for line in open(HERE.parent / "oracle/out/coinbase.txt"):
    p = line.split()
    if p[1] == "out":
        blocks.setdefault(int(p[0]), []).append((int(p[2]), p[3]))
    else:
        blocks.setdefault(int(p[0]), [])

out = ["# GENERATED by gen_data.py: recipient scripts and sampled mainnet coinbase outputs.",
       "import Base", "import ./params.bend as P", "",
       f"def fr_scripts() -> +List<String>:\n  {slist(fr)}\n",
       f"def bp_scripts() -> +List<String>:\n  {slist(bp)}\n",
       f'def zf_script() -> String:\n  "{script(zf)}"\n',
       f'def mg_script() -> String:\n  "{script(mg)}"\n',
       f'def zcg_script() -> String:\n  "{script(zcg)}"\n',
       f'def disbursement_script() -> String:\n  "{script(disb)}"\n',
       "def blocks() -> +List<P.Block>:",
       "  [" + ",\n   ".join(f"P.Block{{U32.to_nat({h}), [" + ", ".join(f'P.Out{{{nat(v)}, "{s}"}}' for v, s in outs) + "]}" for h, outs in sorted(blocks.items())) + "]", ""]
(HERE / "data.bend").write_text("\n".join(out))
print(f"{len(blocks)} blocks, {sum(len(o) for o in blocks.values())} outputs; FR {len(fr)} BP {len(bp)} addresses")
