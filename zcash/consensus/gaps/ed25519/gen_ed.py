def q(v):
    return f"Q{{{v >> 32}, {v & M32}}}"


def rotr_expr(n, h, l):
    """(hi, lo) expressions of rotr64((h, l), n)."""
    if n >= 32:
        h, l = l, h
        n -= 32
    if n == 0:
        return h, l
    return (f"(({h} >> {n}n) .|. ({l} << {32 - n}n))", f"(({l} >> {n}n) .|. ({h} << {32 - n}n))")


def shr_expr(n, h, l):
    assert 0 < n < 32
    return (f"({h} >> {n}n)", f"(({l} >> {n}n) .|. ({h} << {32 - n}n))")


def sig_fn(name, parts):
    hs, ls = [], []
    for kind, n in parts:
        a, b = (rotr_expr if kind == "r" else shr_expr)(n, "h", "l")
        hs.append(a)
        ls.append(b)
    return (f"def {name}(x: Q) -> Q:\n  Q{{+h, +l}} = x\n"
            f"  Q{{({' .^. '.join(hs)} : U32), ({' .^. '.join(ls)} : U32)}}\n")


