P = 2**255 - 19
R = 1 << 256
M32 = (1 << 32) - 1


def mont(x):
    v = x * R % P
    return "F.Fp{" + ", ".join(str((v >> (32 * i)) & M32) for i in range(8)) + "}"


def sqrt_m1():
    return pow(2, (P - 1) // 4, P)


D = (-121665 * pow(121666, -1, P)) % P
I = sqrt_m1()
assert I * I % P == P - 1
BY = 4 * pow(5, -1, P) % P
xx = (BY * BY - 1) * pow(D * BY * BY + 1, -1, P) % P
BX = pow(xx, (P + 3) // 8, P)
if BX * BX % P != xx:
    BX = BX * I % P
assert BX * BX % P == xx
if BX & 1:
    BX = P - BX
assert BX == 15112221349535400772501151409588531511454012693041857206046113283949847762202


