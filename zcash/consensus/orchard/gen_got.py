#!/usr/bin/env python3
"""got_roots.bend: the chunk roots Bend printed in chunk runs (logs/chunks_*.log), in order."""
import re, struct, glob, pathlib, sys
HERE = pathlib.Path(__file__).parent
got = {}
for f in glob.glob(str(HERE / "logs/chunks_*.log")):
    for m in re.finditer(r"chunk (\d+) subtree root ([0-9a-f]{64})", open(f).read()):
        got[int(m[1])] = m[2]
n = 0
while n in got: n += 1
def w(h):
    b = bytes.fromhex(h)
    return "Wd.W{" + ", ".join(str(struct.unpack_from("<I", b, 4 * i)[0]) for i in range(8)) + "}"
(HERE / "got_roots.bend").write_text("# GENERATED by gen_got.py from Bend's own chunk-run output.\nimport Base\nimport ../../halo2/lib/words.bend as Wd\n\n"
    "def got_roots() -> +List<Wd.W>:\n  [" + ", ".join(w(got[i]) for i in range(n)) + "]\n")
print(n, "contiguous chunk roots")
