#!/usr/bin/env python3
"""Expected values for orchard_main.bend: the chain's 770 level-16 Orchard subtree roots
(lightwalletd GetSubtreeRoots) and its Orchard tree states (GetTreeState); and the real Orchard anchors with their (untrusted) block hints from
find_hints.py, plus three tampered cases."""
import struct, pathlib
HERE = pathlib.Path(__file__).parent
O = HERE.parent / "oracle/out"

def w(hexs):
    b = bytes.fromhex(hexs)
    return "Wd.W{" + ", ".join(str(struct.unpack_from("<I", b, 4 * i)[0]) for i in range(8)) + "}"

subs = [l.split() for l in open(O / "orchard_subtrees.txt")]
cps = [l.split() for l in open(O / "orchard_trees.txt")]
lines = ["# GENERATED by gen_inputs.py.", "import Base", "import ../../halo2/lib/words.bend as Wd", "",
         "type CP is Data:", "  CP{height: U32, size: U32, root: Wd.W}", "",
         "def subtree_roots() -> +List<Wd.W>:", "  [" + ", ".join(w(r) for _, _, r in subs) + "]", "",
         "def checkpoints() -> +List<CP>:", "  [" + ", ".join(f"CP{{{h}, {n}, {w(r)}}}" for h, n, r in cps) + "]", ""]
hints = [l.split() for l in open(HERE / "anchor_hints.txt")] if (HERE / "anchor_hints.txt").exists() else []
axs = [(n, int(b), a, int(h), int(sz)) for n, b, a, h, sz in hints]
if axs:
    n, b, a, h, sz = axs[0]
    axs += [("tamper_random_anchor", b, "11" * 32, h, sz),           # no block ends with this root
            ("tamper_same_block_anchor", h, a, h, sz),             # the root of its own block
            ("tamper_wrong_size_hint", b, a, h, sz - 1)]           # hint size not the block's end
lines += ["type Ax is Data:", "  Ax{name: String, block: Nat, anchor: Wd.W, height: Nat, size: Nat}", "",
          "def anchors() -> +List<Ax>:",
          "  [" + ", ".join(f'Ax{{"{n}", U32.to_nat({b}), {w(a)}, U32.to_nat({h}), U32.to_nat({sz})}}' for n, b, a, h, sz in axs) + "]", ""]
(HERE / "inputs.bend").write_text("\n".join(lines))
print(len(subs), "subtree roots,", len(cps), "checkpoints")
