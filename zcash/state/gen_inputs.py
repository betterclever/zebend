#!/usr/bin/env python3
"""Prepare Bend inputs from the oracle's mainnet data (no hashing here):
  oracle/out/leaves.bin (68-byte records: height, cm_x, rho) -> out/cmx.bin (32-byte cm_x records)
  oracle/out/treestates.txt (the chain's own roots via lightwalletd GetTreeState) -> checkpoints.bend
"""
import os
os.makedirs("out", exist_ok=True)
raw = open("oracle/out/leaves.bin", "rb").read()
assert len(raw) % 68 == 0
with open("out/cmx.bin", "wb") as f:
    for i in range(0, len(raw), 68):
        f.write(raw[i + 4:i + 36])
n = len(raw) // 68
def words(h):
    b = bytes.fromhex(h)
    return "Wd.W{" + ", ".join(str(int.from_bytes(b[4*i:4*i+4], "little")) for i in range(8)) + "}"
cps = [l.split() for l in open("oracle/out/treestates.txt")]
out = ["# GENERATED by gen_inputs.py from lightwalletd GetTreeState (the chain's own Ironwood roots).",
       "import Base", "import ../halo2/lib/words.bend as Wd", "",
       "type CP is Data:", "  CP{height: U32, size: U32, root: Wd.W}", "",
       f"def leaf_count() -> U32:", f"  {n}", "",
       "def checkpoints() -> +List<CP>:",
       "  [" + ", ".join(f"CP{{{h}, {s}, {words(r)}}}" for h, s, r in cps) + "]", ""]
open("checkpoints.bend", "w").write("\n".join(out))
print(f"{n} leaves -> out/cmx.bin; {len(cps)} checkpoints -> checkpoints.bend")
