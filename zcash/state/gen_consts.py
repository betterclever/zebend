#!/usr/bin/env python3
"""Turn oracle/out/sinsemilla_consts.txt into consts.bend.

The Sinsemilla generators are *exported* from the Rust oracle (sinsemilla crate's
SINSEMILLA_S table, and Q = hash_to_curve("z.cash:SinsemillaQ")("z.cash:Orchard-MerkleCRH")).
Bend re-checks that every one of them is on the Pallas curve (see sinsemilla.bend) but
does not re-derive them with hash-to-curve. All hashing of tree nodes happens in Bend.
Usage: gen_consts.py oracle/out/sinsemilla_consts.txt consts.bend
"""
import sys

src, dst = sys.argv[1], sys.argv[2]
kv = {}
crh = []
for line in open(src):
    parts = line.split()
    if parts[0].startswith("crh"):
        crh.append(parts[1:])
    else:
        kv[parts[0]] = parts[1]


def words(h):
    b = bytes.fromhex(h)
    ws = [int.from_bytes(b[4 * i:4 * i + 4], "little") for i in range(8)]
    return "Wd.W{" + ", ".join(str(w) for w in ws) + "}"


out = [
    "# GENERATED by gen_consts.py from oracle/out/sinsemilla_consts.txt. Do not edit.",
    "# Sinsemilla constants exported by the Rust oracle (see gen_consts.py).",
    "import Base",
    "import ../halo2/lib/words.bend as Wd",
    "",
    "type XY is Data:",
    "  XY{x: Wd.W, y: Wd.W}",
    "",
    "def q() -> XY:",
    f"  XY{{{words(kv['Q_x'])}, {words(kv['Q_y'])}}}",
    "",
]
CH = 32
for c in range(1024 // CH):
    out.append(f"def s_part{c}() -> +List<XY>:")
    items = ", ".join(f"XY{{{words(kv[f'S{j}_x'])}, {words(kv[f'S{j}_y'])}}}"
                      for j in range(c * CH, (c + 1) * CH))
    out.append(f"  [{items}]")
    out.append("")
out.append("# The 1024 S generators in index order.")
out.append("def s_list() -> +List<XY>:")
expr = "Nil{}"
for c in reversed(range(1024 // CH)):
    expr = f"List.append(&2, XY, s_part{c}(), {expr})" if expr != "Nil{}" else f"s_part{c}()"
out.append(f"  {expr}")
out.append("")
out.append("# Empty subtree roots from the oracle, index = level (0 = the uncommitted leaf 2).")
out.append("def empty_roots_oracle() -> +List<Wd.W>:")
out.append("  [" + ", ".join(words(kv[f"empty{l}"]) for l in range(33)) + "]")
out.append("")
out.append("type CrhVec is Data:")
out.append("  CrhVec{level: U32, left: Wd.W, right: Wd.W, out: Wd.W}")
out.append("")
out.append("def crh_vectors() -> +List<CrhVec>:")
out.append("  [" + ", ".join(f"CrhVec{{{l}, {words(a)}, {words(b)}, {words(h)}}}" for l, a, b, h in crh) + "]")
open(dst, "w").write("\n".join(out) + "\n")
print(f"wrote {dst}")
