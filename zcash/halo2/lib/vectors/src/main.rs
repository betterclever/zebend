//! Ground truth for the Bend Pasta library, computed with pasta_curves.
//!
//!   cargo run --release -- tests        # writes ../t/field_tests.bend, ../t/curve_tests.bend
//!   cargo run --release -- msm N        # writes out/msm_N.bin (N x (point || scalar) || expected)
//!   cargo run --release -- bench N      # halo2 best_multiexp timings, 1 thread and all threads

use std::{fmt::Write as _, fs, time::Instant};

use ff::{Field, FromUniformBytes, PrimeField};
use group::{Curve, Group, GroupEncoding};
use halo2_proofs::arithmetic::best_multiexp;
use pasta_curves::{pallas, vesta, Fp, Fq};
use rand::{RngCore, SeedableRng};
use rand_chacha::ChaCha20Rng;

const CASES: usize = 6;

fn words(b: &[u8]) -> String {
    let w: Vec<String> = b.chunks(4).map(|c| u32::from_le_bytes(c.try_into().unwrap()).to_string()).collect();
    format!("Wd.W{{{}}}", w.join(", "))
}

struct Out {
    defs: String,
    names: Vec<String>,
}

impl Out {
    fn new() -> Self {
        Out { defs: String::new(), names: vec![] }
    }
    /// A test: `body` is a Bend expression of type Bool.
    fn test(&mut self, name: &str, body: String) {
        let id = format!("t{}", self.names.len());
        writeln!(self.defs, "# {name}\ndef {id}() -> Bool:\n  {body}\n").unwrap();
        self.names.push(name.to_string());
    }
    fn write(self, path: &str, imports: &str) {
        let mut s = format!("# GENERATED by vectors/src/main.rs from pasta_curves. Do not edit.\nimport Base\nimport ../words.bend as Wd\n{imports}\n");
        s += &self.defs;
        s += "def line(b: Bool, name: String) -> String:\n  match b:\n    case True{}:\n      \"ok   \" ++ name\n    case False{}:\n      \"FAIL \" ++ name\n\n";
        s += "def main() -> IO(Unit):\n  do IO<Unit>:\n";
        for (i, n) in self.names.iter().enumerate() {
            writeln!(s, "    IO.print(line(t{i}(), \"{n}\"))").unwrap();
        }
        fs::write(path, s).unwrap();
    }
}

/// Field tests for one field. `m` is the Bend module alias ("Fp"/"Fq").
fn field_tests<F: PrimeField<Repr = [u8; 32]> + FromUniformBytes<64>>(o: &mut Out, m: &str, rng: &mut ChaCha20Rng) {
    let w = |x: F| words(x.to_repr().as_ref());
    let e = |x: F| format!("{m}.from_words({})", w(x));
    let eqw = |expr: String, want: F| format!("Wd.is_eq({m}.to_words({expr}), {})", w(want));
    for i in 0..CASES {
        let a = F::random(&mut *rng);
        let b = F::random(&mut *rng);
        o.test(&format!("{m} add {i}"), eqw(format!("{m}.add({}, {})", e(a), e(b)), a + b));
        o.test(&format!("{m} sub {i}"), eqw(format!("{m}.sub({}, {})", e(a), e(b)), a - b));
        o.test(&format!("{m} mul {i}"), eqw(format!("{m}.mul({}, {})", e(a), e(b)), a * b));
        o.test(&format!("{m} sqr {i}"), eqw(format!("{m}.sqr({})", e(a)), a.square()));
        o.test(&format!("{m} neg {i}"), eqw(format!("{m}.neg({})", e(a)), -a));
        o.test(&format!("{m} inv {i}"), eqw(format!("{m}.inv({})", e(a)), a.invert().unwrap()));
        let ex = F::random(&mut *rng);
        let mut exp_u64 = [0u64; 4];
        for (j, c) in ex.to_repr().chunks(8).enumerate() {
            exp_u64[j] = u64::from_le_bytes(c.try_into().unwrap());
        }
        o.test(&format!("{m} pow {i}"), eqw(format!("{m}.pow({}, {})", e(a), w(ex)), a.pow_vartime(exp_u64)));
        let mut wide = [0u8; 64];
        rng.fill_bytes(&mut wide);
        o.test(
            &format!("{m} from_wide {i}"),
            eqw(format!("{m}.from_wide({}, {})", words(&wide[..32]), words(&wide[32..])), F::from_uniform_bytes(&wide)),
        );
        // sqrt of a square: either root is fine, so check the square.
        let sq = a.square();
        o.test(
            &format!("{m} sqrt {i}"),
            format!("{m}.is_eq({m}.sqr(Maybe.default(&2, {m}.{m}, {m}.sqrt({}), {m}.zero())), {})", e(sq), e(sq)),
        );
    }
    // Non-squares have no root.
    let mut ns = F::random(&mut *rng);
    while bool::from(ns.sqrt().is_some()) {
        ns = F::random(&mut *rng);
    }
    o.test(&format!("{m} sqrt non-square"), format!("Maybe.is_none(&2, {m}.{m}, {m}.sqrt({}))", e(ns)));
    // from_words reduces values >= m (any 256-bit input).
    let mut big = [0xffu8; 32];
    big[0] = 0x17;
    let mut wide = [0u8; 64];
    wide[..32].copy_from_slice(&big);
    o.test(&format!("{m} from_words reduces 2^256-233"), eqw(format!("{m}.from_words({})", words(&big)), F::from_uniform_bytes(&wide)));
    o.test(&format!("{m} from_u32"), eqw(format!("{m}.from_u32(123456789)"), F::from(123456789u64)));
    o.test(&format!("{m} inv 1"), eqw(format!("{m}.inv({m}.one())"), F::ONE));
}

/// Curve tests. `cm` = curve alias ("V"/"P"), `sm` = scalar field alias.
fn curve_tests<C>(o: &mut Out, cm: &str, sm: &str, rng: &mut ChaCha20Rng)
where
    C: Group + GroupEncoding<Repr = [u8; 32]> + Curve,
    C::Scalar: PrimeField<Repr = [u8; 32]>,
{
    let enc = |p: C| words(p.to_bytes().as_ref());
    let pt = |p: C| format!("Maybe.default(&2, {cm}.Pt, {cm}.decompress({}), {cm}.identity())", enc(p));
    let is = |expr: String, want: C| format!("Wd.is_eq({cm}.encode({expr}), {})", enc(want));
    let _ = sm;
    for i in 0..CASES {
        let p = C::random(&mut *rng);
        let q = C::random(&mut *rng);
        let s = C::Scalar::random(&mut *rng);
        o.test(&format!("{cm} decompress/encode {i}"), is(pt(p), p));
        o.test(&format!("{cm} add {i}"), is(format!("{cm}.add({}, {})", pt(p), pt(q)), p + q));
        o.test(&format!("{cm} double {i}"), is(format!("{cm}.double({})", pt(p)), p.double()));
        o.test(&format!("{cm} add self {i}"), is(format!("{cm}.add({}, {})", pt(p), pt(p)), p.double()));
        o.test(&format!("{cm} neg {i}"), is(format!("{cm}.neg({})", pt(p)), -p));
        o.test(&format!("{cm} sub {i}"), is(format!("{cm}.sub({}, {})", pt(p), pt(q)), p - q));
        o.test(&format!("{cm} p + -p = 0 {i}"), is(format!("{cm}.add({}, {}.neg({}))", pt(p), cm, pt(p)), C::identity()));
        o.test(&format!("{cm} add_aff {i}"), is(format!("{cm}.add_aff({}, {cm}.to_aff({}))", pt(p), pt(q)), p + q));
        o.test(&format!("{cm} scalar_mul {i}"), is(format!("{cm}.scalar_mul({}, {})", pt(p), words(s.to_repr().as_ref())), p * s));
        o.test(&format!("{cm} is_eq {i}"), format!("{cm}.is_eq({cm}.add({}, {}), {cm}.add({}, {}))", pt(p), pt(q), pt(q), pt(p)));
    }
    let p = C::random(&mut *rng);
    o.test(&format!("{cm} 0 + p"), is(format!("{cm}.add({cm}.identity(), {})", pt(p)), p));
    o.test(&format!("{cm} double 0"), is(format!("{cm}.double({cm}.identity())"), C::identity()));
    o.test(&format!("{cm} encode 0"), is(format!("{cm}.identity()"), C::identity()));
    o.test(&format!("{cm} decompress 0"), format!("{cm}.is_identity({})", pt(C::identity())));
    o.test(&format!("{cm} scalar_mul by 0"), is(format!("{cm}.scalar_mul({}, Wd.zero())", pt(p)), C::identity()));
    // Invalid encodings: x = 0 with the sign bit, x >= modulus, x off the curve.
    let mut bad = [0u8; 32];
    bad[31] = 0x80;
    o.test(&format!("{cm} reject x=0 sign=1"), format!("Maybe.is_none(&2, {cm}.Pt, {cm}.decompress({}))", words(&bad)));
    let mut big = [0xffu8; 32];
    big[31] = 0x7f;
    o.test(&format!("{cm} reject x >= modulus"), format!("Maybe.is_none(&2, {cm}.Pt, {cm}.decompress({}))", words(&big)));
    let mut off = [0u8; 32];
    let mut found = 0;
    for t in 1..1000u32 {
        off[..4].copy_from_slice(&t.to_le_bytes());
        if bool::from(C::from_bytes(&off).is_none()) {
            found = t;
            break;
        }
    }
    off[..4].copy_from_slice(&found.to_le_bytes());
    o.test(&format!("{cm} reject off-curve x={found}"), format!("Maybe.is_none(&2, {cm}.Pt, {cm}.decompress({}))", words(&off)));
}

fn tests() {
    let mut rng = ChaCha20Rng::seed_from_u64(2026);
    let mut o = Out::new();
    field_tests::<Fp>(&mut o, "Fp", &mut rng);
    field_tests::<Fq>(&mut o, "Fq", &mut rng);
    o.write("../t/field_tests.bend", "import ../fp.bend as Fp\nimport ../fq.bend as Fq\n");
    let mut o = Out::new();
    curve_tests::<vesta::Point>(&mut o, "V", "Fp", &mut rng);
    curve_tests::<pallas::Point>(&mut o, "P", "Fq", &mut rng);
    o.write("../t/curve_tests.bend", "import ../vesta.bend as V\nimport ../pallas.bend as P\n");
}

fn instance(n: usize, seed: u64) -> (Vec<vesta::Affine>, Vec<Fp>) {
    let mut rng = ChaCha20Rng::seed_from_u64(seed);
    let pts: Vec<vesta::Point> = (0..n).map(|_| vesta::Point::random(&mut rng)).collect();
    let mut aff = vec![vesta::Affine::default(); n];
    vesta::Point::batch_normalize(&pts, &mut aff);
    let sc = (0..n).map(|_| Fp::random(&mut rng)).collect();
    (aff, sc)
}

fn msm(n: usize) {
    let (bases, coeffs) = instance(n, n as u64);
    let want = best_multiexp(&coeffs, &bases);
    let naive = bases.iter().zip(&coeffs).fold(vesta::Point::identity(), |acc, (b, c)| acc + *b * c);
    assert_eq!(want, naive);
    let mut out = Vec::with_capacity(n * 64 + 32);
    for (b, c) in bases.iter().zip(&coeffs) {
        out.extend_from_slice(&b.to_bytes());
        out.extend_from_slice(&c.to_repr());
    }
    out.extend_from_slice(&want.to_bytes());
    fs::create_dir_all("out").unwrap();
    fs::write(format!("out/msm_{n}.bin"), out).unwrap();
    println!("wrote out/msm_{n}.bin; expected {}", hex(&want.to_bytes()));
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn bench(n: usize) {
    let (bases, coeffs) = instance(n, n as u64);
    for threads in [1, rayon::current_num_threads()] {
        let pool = rayon::ThreadPoolBuilder::new().num_threads(threads).build().unwrap();
        let mut best = f64::MAX;
        for _ in 0..5 {
            let t = Instant::now();
            let r = pool.install(|| best_multiexp(&coeffs, &bases));
            std::hint::black_box(r);
            best = best.min(t.elapsed().as_secs_f64());
        }
        println!("rust halo2 best_multiexp n={n} threads={threads}: {:.3} ms", best * 1e3);
    }
    let t = Instant::now();
    let mut acc = vesta::Point::identity();
    for (b, c) in bases.iter().zip(&coeffs) {
        acc += *b * c;
    }
    std::hint::black_box(acc);
    println!("rust naive sum of scalar mults n={n} threads=1: {:.3} ms", t.elapsed().as_secs_f64() * 1e3);
    // single field mul cost
    let mut x = Fp::random(&mut ChaCha20Rng::seed_from_u64(1));
    let y = x.double();
    let t = Instant::now();
    for _ in 0..10_000_000 {
        x = x * y;
    }
    std::hint::black_box(x);
    println!("rust Fp mul: {:.2} ns", t.elapsed().as_secs_f64() * 1e9 / 1e7);
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    match args.get(1).map(String::as_str) {
        Some("tests") => tests(),
        Some("msm") => msm(args[2].parse().unwrap()),
        Some("bench") => bench(args[2].parse().unwrap()),
        _ => eprintln!("usage: tests | msm N | bench N"),
    }
}
