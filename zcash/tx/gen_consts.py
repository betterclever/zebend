#!/usr/bin/env python3
"""consts.bend: the Orchard generators as labelled constants, from the oracle's
mainnet/constants.txt (GroupHash^P computed by pasta_curves; not recomputed in Bend).
G_SPENDAUTH = GroupHash("z.cash:Orchard", "G"); V_CV, R_CV = GroupHash("z.cash:Orchard-cv", "v" / "r")."""
import pathlib
here = pathlib.Path(__file__).parent
kv = dict(l.split() for l in (here / "mainnet/constants.txt").read_text().splitlines())
out = ["# GENERATED by gen_consts.py from mainnet/constants.txt (oracle). Compressed Pallas points.",
       "import Base", "import ../halo2/lib/words.bend as Wd", ""]
for name, key in (("G_SPENDAUTH", "G_spendauth"), ("V_CV", "V"), ("R_CV", "R")):
    b = bytes.fromhex(kv[key])
    w = [int.from_bytes(b[4 * i:4 * i + 4], "little") for i in range(8)]
    out.append(f"def {name}() -> Wd.W:\n  Wd.W{{{', '.join(map(str, w))}}}\n")
(here / "consts.bend").write_text("\n".join(out))
