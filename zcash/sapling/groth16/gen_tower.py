#!/usr/bin/env python3
"""Generates fq2.bend, fq6.bend, fq12.bend: the BLS12-381 extension tower used by the
bls12_381 crate,
    Fq2  = Fq[u]  / (u^2 + 1)
    Fq6  = Fq2[v] / (v^3 - (u + 1))
    Fq12 = Fq6[w] / (w^2 - v)
Hand-written formulas (Karatsuba / Chung-Hasan squaring / the crate's sparse mul_by_01,
mul_by_1, mul_by_014) with the Frobenius constants and the Fq2 square-root exponent chains
generated here. Values are the same field elements the crate computes (formulas may differ,
results cannot).

  python3 gen_tower.py
"""
import pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "ref"))
import gen_fq
from bls import P, pow2, G6_1, G6_2, G12

R = 1 << 384


def fq_lit(v):
    return "F.Fq{" + ", ".join(str(w) for w in gen_fq.words(v * R % P)) + "}"


def fq2_lit(c):
    return f"Fq2{{{fq_lit(c[0])}, {fq_lit(c[1])}}}"


FQ2 = '''# GENERATED by gen_tower.py. Do not edit.
# Fq2 = Fq[u] / (u^2 + 1), elements c0 + c1 u (Montgomery-form coefficients).
import Base
import ./fq.bend as F

type Fq2 is Data:
  Fq2{c0: F.Fq, c1: F.Fq}

def mk(a: F.Fq, b: F.Fq) -> Fq2:
  Fq2{a, b}

def zero() -> Fq2:
  Fq2{F.zero(), F.zero()}

def one() -> Fq2:
  Fq2{F.one(), F.zero()}

def add(a: Fq2, b: Fq2) -> Fq2:
  Fq2{a0, a1} = a
  Fq2{b0, b1} = b
  Fq2{F.add(a0, b0), F.add(a1, b1)}

def sub(a: Fq2, b: Fq2) -> Fq2:
  Fq2{a0, a1} = a
  Fq2{b0, b1} = b
  Fq2{F.sub(a0, b0), F.sub(a1, b1)}

def neg(a: Fq2) -> Fq2:
  Fq2{a0, a1} = a
  Fq2{F.neg(a0), F.neg(a1)}

def dbl(a: Fq2) -> Fq2:
  Fq2{+a0, +a1} = a
  Fq2{F.add(a0, a0), F.add(a1, a1)}

# Complex conjugate = Frobenius (a + b u)^p = a - b u.
def conj(a: Fq2) -> Fq2:
  Fq2{a0, a1} = a
  Fq2{a0, F.neg(a1)}

# Karatsuba: 3 Fq multiplications.
def mul(a: Fq2, b: Fq2) -> Fq2:
  Fq2{+a0, +a1} = a
  Fq2{+b0, +b1} = b
  +t0 = F.mul(a0, b0)
  +t1 = F.mul(a1, b1)
  t2 = F.mul(F.add(a0, a1), F.add(b0, b1))
  Fq2{F.sub(t0, t1), F.sub(F.sub(t2, t0), t1)}

# (a0 + a1 u)^2 = (a0 + a1)(a0 - a1) + 2 a0 a1 u.
def sqr(a: Fq2) -> Fq2:
  Fq2{+a0, +a1} = a
  +t = F.mul(a0, a1)
  Fq2{F.mul(F.add(a0, a1), F.sub(a0, a1)), F.add(t, t)}

# a * k for k in Fq.
def mul_fq(a: Fq2, +k: F.Fq) -> Fq2:
  Fq2{a0, a1} = a
  Fq2{F.mul(a0, k), F.mul(a1, k)}

# a * (u + 1)
def mul_nr(a: Fq2) -> Fq2:
  Fq2{+a0, +a1} = a
  Fq2{F.sub(a0, a1), F.add(a0, a1)}

def inv(a: Fq2) -> Fq2:
  Fq2{+a0, +a1} = a
  +t = F.inv(F.add(F.sqr(a0), F.sqr(a1)))
  Fq2{F.mul(a0, t), F.neg(F.mul(a1, t))}

def eq(a: Fq2, b: Fq2) -> U32:
  Fq2{a0, a1} = a
  Fq2{b0, b1} = b
  (F.eq(a0, b0) .&. F.eq(a1, b1) : U32)

def is_eq(a: Fq2, b: Fq2) -> Bool:
  U32.is_eq(eq(a, b), 1)

def is_zero(a: Fq2) -> Bool:
  U32.is_eq(eq(a, zero()), 1)

def sel(+c: U32, a: Fq2, b: Fq2) -> Fq2:
  Fq2{a0, a1} = a
  Fq2{b0, b1} = b
  Fq2{F.sel(c, a0, b0), F.sel(c, a1, b1)}

def sqr_n(n: Nat, x: Fq2) -> Fq2:
  match n:
    case 0n:
      x
    case 1n+k:
      sqr_n(k, sqr(x))

# 1 if the canonical value is lexicographically largest (the crate's rule: c1 > (p-1)/2,
# or c1 == 0 and c0 > (p-1)/2).
def largest(a: Fq2) -> U32:
  Fq2{a0, a1} = a
  +r0 = F.to_raw(a0)
  +r1 = F.to_raw(a1)
  +z1 = F.eq(r1, F.zero())
  ((1 - F.lt_half(r1)) .|. (z1 .&. (1 - F.lt_half(r0))) : U32)

'''

FQ2_TAIL = '''
def maybe_if(b: Bool, r: Fq2) -> Maybe<&2, Fq2>:
  match b:
    case True{}:
      Some{r}
    case False{}:
      None{}

def sqrt_pick(b: Bool, +x0: Fq2, alpha: Fq2) -> Fq2:
  match b:
    case True{}:
      Fq2{x00, x01} = x0
      Fq2{F.neg(x01), x00}
    case False{}:
      mul(pow_pm1d2(add(alpha, one())), x0)

# Square root (Algorithm 9 of eprint 2012/685, as the crate); None if a is not a square.
def sqrt(+a: Fq2) -> Maybe<&2, Fq2>:
  +a1 = pow_pm3d4(a)
  +alpha = mul(sqr(a1), a)
  +x0 = mul(a1, a)
  +s = sqrt_pick(is_eq(alpha, neg(one())), x0, alpha)
  maybe_if(is_eq(sqr(s), a), s)
'''

FQ6 = '''# GENERATED by gen_tower.py. Do not edit.
# Fq6 = Fq2[v] / (v^3 - (u + 1)), elements c0 + c1 v + c2 v^2.
import Base
import ./fq.bend as F
import ./fq2.bend as E

# Fq6B is never built: its self-reference makes Bend store Fq6 values boxed (one word),
# which keeps Fq12 (two Fq6) and the functions on it under Bend's 247-word arity limit.
type Fq6 is Data:
  Fq6{c0: E.Fq2, c1: E.Fq2, c2: E.Fq2}
  Fq6B{b: Fq6}

def zero() -> Fq6:
  Fq6{E.zero(), E.zero(), E.zero()}

def one() -> Fq6:
  Fq6{E.one(), E.zero(), E.zero()}

def add(a: Fq6, b: Fq6) -> Fq6:
  match a b:
    case Fq6{a0, a1, a2} Fq6{b0, b1, b2}:
      Fq6{E.add(a0, b0), E.add(a1, b1), E.add(a2, b2)}
    case _ _:
      zero()

def sub(a: Fq6, b: Fq6) -> Fq6:
  match a b:
    case Fq6{a0, a1, a2} Fq6{b0, b1, b2}:
      Fq6{E.sub(a0, b0), E.sub(a1, b1), E.sub(a2, b2)}
    case _ _:
      zero()

def neg(a: Fq6) -> Fq6:
  match a:
    case Fq6{a0, a1, a2}:
      Fq6{E.neg(a0), E.neg(a1), E.neg(a2)}
    case _:
      zero()

# Karatsuba: 6 Fq2 multiplications.
def mul(a: Fq6, b: Fq6) -> Fq6:
  match a b:
    case Fq6{+a0, +a1, +a2} Fq6{+b0, +b1, +b2}:
      +v0 = E.mul(a0, b0)
      +v1 = E.mul(a1, b1)
      +v2 = E.mul(a2, b2)
      t0 = E.sub(E.sub(E.mul(E.add(a1, a2), E.add(b1, b2)), v1), v2)
      t1 = E.sub(E.sub(E.mul(E.add(a0, a1), E.add(b0, b1)), v0), v1)
      t2 = E.sub(E.add(E.sub(E.mul(E.add(a0, a2), E.add(b0, b2)), v0), v1), v2)
      Fq6{E.add(v0, E.mul_nr(t0)), E.add(t1, E.mul_nr(v2)), t2}
    case _ _:
      zero()

# Chung-Hasan SQR2 (the crate's square).
def sqr(a: Fq6) -> Fq6:
  match a:
    case Fq6{+a0, +a1, +a2}:
      +s0 = E.sqr(a0)
      +ab = E.mul(a0, a1)
      +s1 = E.add(ab, ab)
      +s2 = E.sqr(E.add(E.sub(a0, a1), a2))
      +bc = E.mul(a1, a2)
      +s3 = E.add(bc, bc)
      +s4 = E.sqr(a2)
      Fq6{E.add(E.mul_nr(s3), s0), E.add(E.mul_nr(s4), s1), E.sub(E.sub(E.add(E.add(s1, s2), s3), s0), s4)}
    case _:
      zero()

# a * v
def mul_nr(a: Fq6) -> Fq6:
  match a:
    case Fq6{a0, a1, a2}:
      Fq6{E.mul_nr(a2), a0, a1}
    case _:
      zero()

# a * (c1 v)
def mul_by_1(a: Fq6, +c1: E.Fq2) -> Fq6:
  match a:
    case Fq6{a0, a1, a2}:
      Fq6{E.mul_nr(E.mul(a2, c1)), E.mul(a0, c1), E.mul(a1, c1)}
    case _:
      zero()

# a * (c0 + c1 v)
def mul_by_01(a: Fq6, +c0: E.Fq2, +c1: E.Fq2) -> Fq6:
  match a:
    case Fq6{+a0, +a1, +a2}:
      +aa = E.mul(a0, c0)
      +bb = E.mul(a1, c1)
      t1 = E.add(E.mul_nr(E.mul(a2, c1)), aa)
      t2 = E.sub(E.sub(E.mul(E.add(c0, c1), E.add(a0, a1)), aa), bb)
      t3 = E.add(E.mul(a2, c0), bb)
      Fq6{t1, t2, t3}
    case _:
      zero()

def inv(a: Fq6) -> Fq6:
  match a:
    case Fq6{+a0, +a1, +a2}:
      +c0 = E.sub(E.sqr(a0), E.mul_nr(E.mul(a1, a2)))
      +c1 = E.sub(E.mul_nr(E.sqr(a2)), E.mul(a0, a1))
      +c2 = E.sub(E.sqr(a1), E.mul(a0, a2))
      +t = E.inv(E.add(E.mul_nr(E.add(E.mul(a1, c2), E.mul(a2, c1))), E.mul(a0, c0)))
      Fq6{E.mul(t, c0), E.mul(t, c1), E.mul(t, c2)}
    case _:
      zero()

# (u + 1)^((p - 1) / 3) and (u + 1)^(2 (p - 1) / 3)
def frob_c1() -> E.Fq2:
  E.{G61}

def frob_c2() -> E.Fq2:
  E.{G62}

def frob(a: Fq6) -> Fq6:
  match a:
    case Fq6{a0, a1, a2}:
      Fq6{E.conj(a0), E.mul(E.conj(a1), frob_c1()), E.mul(E.conj(a2), frob_c2())}
    case _:
      zero()

# a * g for g in Fq2
def mul_fq2(a: Fq6, +g: E.Fq2) -> Fq6:
  match a:
    case Fq6{a0, a1, a2}:
      Fq6{E.mul(a0, g), E.mul(a1, g), E.mul(a2, g)}
    case _:
      zero()

def eq(a: Fq6, b: Fq6) -> U32:
  match a b:
    case Fq6{a0, a1, a2} Fq6{b0, b1, b2}:
      (E.eq(a0, b0) .&. E.eq(a1, b1) .&. E.eq(a2, b2) : U32)
    case _ _:
      0
'''

FQ12 = '''# GENERATED by gen_tower.py. Do not edit.
# Fq12 = Fq6[w] / (w^2 - v), elements c0 + c1 w.
import Base
import ./fq.bend as F
import ./fq2.bend as E
import ./fq6.bend as S

type Fq12 is Data:
  Fq12{c0: S.Fq6, c1: S.Fq6}

def one() -> Fq12:
  Fq12{S.one(), S.zero()}

# Karatsuba: 3 Fq6 multiplications.
def mul(a: Fq12, b: Fq12) -> Fq12:
  Fq12{+a0, +a1} = a
  Fq12{+b0, +b1} = b
  +aa = S.mul(a0, b0)
  +bb = S.mul(a1, b1)
  c1 = S.sub(S.sub(S.mul(S.add(a0, a1), S.add(b0, b1)), aa), bb)
  Fq12{S.add(aa, S.mul_nr(bb)), c1}

# The crate's square: 2 Fq6 multiplications.
def sqr(a: Fq12) -> Fq12:
  Fq12{+a0, +a1} = a
  +ab = S.mul(a0, a1)
  +c0 = S.mul(S.add(S.mul_nr(a1), a0), S.add(a0, a1))
  Fq12{S.sub(S.sub(c0, ab), S.mul_nr(ab)), S.add(ab, ab)}

def conj(a: Fq12) -> Fq12:
  Fq12{a0, a1} = a
  Fq12{a0, S.neg(a1)}

def inv(a: Fq12) -> Fq12:
  Fq12{+a0, +a1} = a
  +t = S.inv(S.sub(S.sqr(a0), S.mul_nr(S.sqr(a1))))
  Fq12{S.mul(a0, t), S.neg(S.mul(a1, t))}

# (u + 1)^((p - 1) / 6)
def frob_w() -> E.Fq2:
  E.{G12}

def frob(a: Fq12) -> Fq12:
  Fq12{a0, a1} = a
  Fq12{S.frob(a0), S.mul_fq2(S.frob(a1), frob_w())}

# f * ((c0 + c1 v) + (c4 v) w): the sparse line multiplication of the Miller loop.
def mul_by_014(f: Fq12, +c0: E.Fq2, +c1: E.Fq2, +c4: E.Fq2) -> Fq12:
  Fq12{+f0, +f1} = f
  +aa = S.mul_by_01(f0, c0, c1)
  +bb = S.mul_by_1(f1, c4)
  t1 = S.sub(S.sub(S.mul_by_01(S.add(f1, f0), c0, E.add(c1, c4)), aa), bb)
  Fq12{S.add(S.mul_nr(bb), aa), t1}

def eq(a: Fq12, b: Fq12) -> U32:
  Fq12{a0, a1} = a
  Fq12{b0, b1} = b
  (S.eq(a0, b0) .&. S.eq(a1, b1) : U32)

def is_eq(a: Fq12, b: Fq12) -> Bool:
  U32.is_eq(eq(a, b), 1)
'''


def main():
    chains = (gen_fq.window_chain("pow_pm3d4", (P - 3) // 4, "a^((p-3)/4)", T="Fq2").replace("(t: pow_pm3d4_T)", "(t: pow_pm3d4_T)")
              + "\n" + gen_fq.window_chain("pow_pm1d2", (P - 1) // 2, "a^((p-1)/2)", T="Fq2"))
    (HERE / "fq2.bend").write_text(FQ2 + chains + FQ2_TAIL)
    (HERE / "fq6.bend").write_text(FQ6.replace("E.{G61}", "E." + fq2_lit(G6_1)).replace("E.{G62}", "E." + fq2_lit(G6_2)))
    (HERE / "fq12.bend").write_text(FQ12.replace("E.{G12}", "E." + fq2_lit(G12)))
    print("wrote fq2.bend fq6.bend fq12.bend")


if __name__ == "__main__":
    main()
