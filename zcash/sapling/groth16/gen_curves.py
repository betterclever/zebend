#!/usr/bin/env python3
"""Generates g1.bend, g2.bend, pairing.bend: BLS12-381 G1 / G2 (complete projective
formulas of Renes-Costello-Batina, a = 0), point decoding as the bls12_381 crate does
(flags, canonical coordinates, square root, sign, subgroup check by the crate's
endomorphism tests), the optimal ate Miller loop with the crate's exact doubling/addition
steps and line scaling, and the crate's final exponentiation.

  python3 gen_curves.py
"""
import pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "ref"))
import gen_fq
from bls import P, X, BETA, PSI_X, PSI_Y

R = 1 << 384


def fq_lit(v):
    return "F.Fq{" + ", ".join(str(w) for w in gen_fq.words(v * R % P)) + "}"


def fq2_lit(c):
    return f"E.Fq2{{{fq_lit(c[0])}, {fq_lit(c[1])}}}"


# Points are scanned by a 64-bit constant (|x| = 0xd201000000010000) as two U32 words.
XH, XL = X >> 32, X & 0xffffffff

CURVE = '''# GENERATED by gen_curves.py. Do not edit.
# BLS12-381 {G}: y^2 = x^3 + {BDOC} over {FIELD}. Complete projective formulas
# (Renes-Costello-Batina 2015, a = 0, b3 = 3b).
import Base
import ./fq.bend as F
import ./fq2.bend as E

type Pt is Data:
  Pt{{x: {T}, y: {T}, z: {T}}}

def curve_b() -> {T}:
  {CB}

type Aff is Data:
  Aff{{x: {T}, y: {T}}}

def mk_aff(x: {T}, y: {T}) -> Aff:
  Aff{{x, y}}

def identity() -> Pt:
  Pt{{{M}.zero(), {M}.one(), {M}.zero()}}

def is_identity(p: Pt) -> Bool:
  Pt{{_, _, z}} = p
  {M}.is_zero(z)

# 3b * a
def mul_b3(+a: {T}) -> {T}:
  +a2 = {M}.add(a, a)
  +a4 = {M}.add(a2, a2)
  +a8 = {M}.add(a4, a4)
  {B3TAIL}

# RCB Algorithm 7: complete projective addition, a = 0.
def add(p: Pt, q: Pt) -> Pt:
  Pt{{+x1, +y1, +z1}} = p
  Pt{{+x2, +y2, +z2}} = q
  +t0 = {M}.mul(x1, x2)
  +t1 = {M}.mul(y1, y2)
  +t2 = {M}.mul(z1, z2)
  t3a = {M}.mul({M}.add(x1, y1), {M}.add(x2, y2))
  +t3 = {M}.sub(t3a, {M}.add(t0, t1))
  t4a = {M}.mul({M}.add(y1, z1), {M}.add(y2, z2))
  +t4 = {M}.sub(t4a, {M}.add(t1, t2))
  x3a = {M}.mul({M}.add(x1, z1), {M}.add(x2, z2))
  y3a = {M}.sub(x3a, {M}.add(t0, t2))
  +t0b = {M}.add({M}.add(t0, t0), t0)
  +t2b = mul_b3(t2)
  +z3a = {M}.add(t1, t2b)
  +t1b = {M}.sub(t1, t2b)
  +y3b = mul_b3(y3a)
  x3 = {M}.sub({M}.mul(t3, t1b), {M}.mul(t4, y3b))
  y3 = {M}.add({M}.mul(t1b, z3a), {M}.mul(y3b, t0b))
  z3 = {M}.add({M}.mul(z3a, t4), {M}.mul(t0b, t3))
  Pt{{x3, y3, z3}}

# RCB Algorithm 8: mixed addition P + Q, Q affine and not the identity (P may be).
def add_aff(p: Pt, q: Aff) -> Pt:
  Pt{{+x1, +y1, +z1}} = p
  Aff{{+x2, +y2}} = q
  +t0a = {M}.mul(x1, x2)
  +t1a = {M}.mul(y1, y2)
  t3a = {M}.mul({M}.add(x2, y2), {M}.add(x1, y1))
  +t3 = {M}.sub(t3a, {M}.add(t0a, t1a))
  +t4 = {M}.add({M}.mul(y2, z1), y1)
  y3a = {M}.add({M}.mul(x2, z1), x1)
  +x3a = {M}.add(t0a, t0a)
  +t0 = {M}.add(x3a, t0a)
  +t2 = mul_b3(z1)
  +z3a = {M}.add(t1a, t2)
  +t1 = {M}.sub(t1a, t2)
  +y3b = mul_b3(y3a)
  x3 = {M}.sub({M}.mul(t3, t1), {M}.mul(t4, y3b))
  y3 = {M}.add({M}.mul(t1, z3a), {M}.mul(y3b, t0))
  z3 = {M}.add({M}.mul(z3a, t4), {M}.mul(t0, t3))
  Pt{{x3, y3, z3}}

# RCB Algorithm 9: complete projective doubling, a = 0.
def double(p: Pt) -> Pt:
  Pt{{+x, +y, +z}} = p
  +t0 = {M}.sqr(y)
  +z3a = {M}.add(t0, t0)
  +z3b = {M}.add(z3a, z3a)
  +z3c = {M}.add(z3b, z3b)
  t1 = {M}.mul(y, z)
  +t2 = mul_b3({M}.sqr(z))
  x3a = {M}.mul(t2, z3c)
  y3a = {M}.add(t0, t2)
  z3 = {M}.mul(t1, z3c)
  +t1b = {M}.add(t2, t2)
  t2b = {M}.add(t1b, t2)
  +t0b = {M}.sub(t0, t2b)
  +x3b = {M}.mul(t0b, {M}.mul(x, y))
  Pt{{{M}.add(x3b, x3b), {M}.add(x3a, {M}.mul(t0b, y3a)), z3}}

def dbl_n(n: Nat, p: Pt) -> Pt:
  match n:
    case 0n:
      p
    case 1n+k:
      dbl_n(k, double(p))

def neg(p: Pt) -> Pt:
  Pt{{x, y, z}} = p
  Pt{{x, {M}.neg(y), z}}

def from_aff(a: Aff) -> Pt:
  Aff{{x, y}} = a
  Pt{{x, y, {M}.one()}}

# Affine coordinates; the identity maps to (0, 0).
def to_aff(p: Pt) -> Aff:
  Pt{{x, y, z}} = p
  +zi = {M}.inv(z)
  Aff{{{M}.mul(x, zi), {M}.mul(y, zi)}}

# Projective equality (handles the identity).
def is_eq(p: Pt, q: Pt) -> Bool:
  Pt{{+x1, +y1, +z1}} = p
  Pt{{+x2, +y2, +z2}} = q
  Bool.and({M}.is_eq({M}.mul(x1, z2), {M}.mul(x2, z1)), {M}.is_eq({M}.mul(y1, z2), {M}.mul(y2, z1)))

def add_if(b: Bool, p: Pt, +q: Pt) -> Pt:
  match b:
    case True{{}}:
      add(p, q)
    case False{{}}:
      p

# acc * 2^n + (top n bits of w) * q, left-to-right double-and-add.
def mul_w(n: Nat, w: U32, acc: Pt, +q: Pt) -> Pt:
  match n:
    case 0n:
      acc
    case 1n+k:
      +w2 = w
      mul_w(k, (w2 << 1n : U32), add_if(U32.is_eq((w2 >> 31n : U32), 1), double(acc), q), q)

# [|x|] p, |x| = 0xd201000000010000 (the BLS parameter, x < 0).
def mul_abs_x(+p: Pt) -> Pt:
  mul_w(32n, {XL}, mul_w(32n, {XH}, identity(), p), p)

# On the curve (affine): y^2 == x^3 + b.
def on_curve(a: Aff) -> Bool:
  Aff{{+x, +y}} = a
  {M}.is_eq({M}.sqr(y), {M}.add({M}.mul({M}.sqr(x), x), curve_b()))
'''

G1_EXTRA = '''
# beta: a non-trivial cube root of unity; phi(x, y) = (beta x, y).
def beta() -> F.Fq:
  {BETA}

# [s] p for a 256-bit scalar given as 8 little-endian U32 words.
def mul_scalar(+p: Pt, w0: U32, w1: U32, w2: U32, w3: U32, w4: U32, w5: U32, w6: U32, w7: U32) -> Pt:
  a7 = mul_w(32n, w7, identity(), p)
  a6 = mul_w(32n, w6, a7, p)
  a5 = mul_w(32n, w5, a6, p)
  a4 = mul_w(32n, w4, a5, p)
  a3 = mul_w(32n, w3, a4, p)
  a2 = mul_w(32n, w2, a3, p)
  a1 = mul_w(32n, w1, a2, p)
  mul_w(32n, w0, a1, p)

# The crate's G1 subgroup test: phi(P) == -[x^2] P.
def in_subgroup(+a: Aff) -> Bool:
  Aff{{+x, +y}} = a
  +p = from_aff(mk_aff(x, y))
  is_eq(neg(mul_abs_x(mul_abs_x(p))), Pt{{F.mul(x, beta()), y, F.one()}})

def some_if(b: Bool, a: Aff) -> Maybe<&2, Aff>:
  match b:
    case True{{}}:
      Some{{a}}
    case False{{}}:
      None{{}}

def pick_y(+flip: U32, +y: F.Fq) -> F.Fq:
  F.sel(flip, F.neg(y), y)

def dec_root(r: Maybe<&2, F.Fq>, +x: F.Fq, +sort: U32) -> Maybe<&2, Aff>:
  match r:
    case Some{{+y}}:
      +a = mk_aff(x, pick_y((F.largest(y) .^. sort : U32), y))
      some_if(in_subgroup(a), a)
    case None{{}}:
      None{{}}

def dec_ok(b: Bool, +x: F.Fq, +sort: U32) -> Maybe<&2, Aff>:
  match b:
    case True{{}}:
      dec_root(F.sqrt(F.add(F.mul(F.sqr(x), x), curve_b())), x, sort)
    case False{{}}:
      None{{}}

# A compressed point as groth16's Proof::read accepts it: compression flag set,
# infinity flag clear (the identity is rejected), x canonical, x^3 + 4 a square,
# y chosen by the sort flag, P in the prime-order subgroup. xr: x's raw words with the
# three flag bits already masked; flags: byte 0 >> 5.
def decode(+flags: U32, +xr: F.Fq) -> Maybe<&2, Aff>:
  +x = F.from_raw(xr)
  +okf = ((flags >> 2n) .&. (1 - ((flags >> 1n) .&. 1)) .&. F.lt_p(xr) : U32)
  dec_ok(U32.is_eq(okf, 1), x, (flags .&. 1 : U32))
'''

G2_EXTRA = '''
def psi_x() -> E.Fq2:
  {PSIX}

def psi_y() -> E.Fq2:
  {PSIY}

# psi(P) = (frob(x) / (u+1)^((p-1)/3), frob(y) / (u+1)^((p-1)/2), frob(z))
def psi(p: Pt) -> Pt:
  Pt{{x, y, z}} = p
  Pt{{E.mul(E.conj(x), psi_x()), E.mul(E.conj(y), psi_y()), E.conj(z)}}

# The crate's G2 subgroup test: psi(P) == [x] P (x < 0).
def in_subgroup(+a: Aff) -> Bool:
  +p = from_aff(a)
  is_eq(psi(p), neg(mul_abs_x(p)))

def some_if(b: Bool, a: Aff) -> Maybe<&2, Aff>:
  match b:
    case True{{}}:
      Some{{a}}
    case False{{}}:
      None{{}}

def dec_root(r: Maybe<&2, E.Fq2>, +x: E.Fq2, +sort: U32) -> Maybe<&2, Aff>:
  match r:
    case Some{{+y}}:
      +a = mk_aff(x, E.sel((E.largest(y) .^. sort : U32), E.neg(y), y))
      some_if(in_subgroup(a), a)
    case None{{}}:
      None{{}}

def dec_ok(b: Bool, +x: E.Fq2, +sort: U32) -> Maybe<&2, Aff>:
  match b:
    case True{{}}:
      dec_root(E.sqrt(E.add(E.mul(E.sqr(x), x), curve_b())), x, sort)
    case False{{}}:
      None{{}}

# As G1.decode; x = x0 + x1 u, encoded x1 (with the flags) then x0. x1r is masked.
def decode(+flags: U32, +x1r: F.Fq, +x0r: F.Fq) -> Maybe<&2, Aff>:
  +x = E.mk(F.from_raw(x0r), F.from_raw(x1r))
  +okf = ((flags >> 2n) .&. (1 - ((flags >> 1n) .&. 1)) .&. F.lt_p(x1r) .&. F.lt_p(x0r) : U32)
  dec_ok(U32.is_eq(okf, 1), x, (flags .&. 1 : U32))
'''


def curve(G, T, M, field, bdoc, b3tail, extra, cb):
    return CURVE.format(G=G, T=T, M=M, FIELD=field, BDOC=bdoc, B3TAIL=b3tail, XL=XL, XH=XH, CB=cb) + extra


def main():
    g1 = curve("G1", "F.Fq", "F", "Fq", "4", "F.add(a8, a4)",
               G1_EXTRA.format(BETA=fq_lit(BETA)), fq_lit(4))
    # b' = 4 (u + 1); 3b' a = 12 (u + 1) a
    g2 = curve("G2", "E.Fq2", "E", "Fq2", "4(u + 1)", "E.mul_nr(E.add(a8, a4))",
               G2_EXTRA.format(PSIX=fq2_lit(PSI_X), PSIY=fq2_lit(PSI_Y)), fq2_lit((4, 4)))
    (HERE / "g1.bend").write_text(g1)
    (HERE / "g2.bend").write_text(g2)
    print("wrote g1.bend g2.bend")


if __name__ == "__main__":
    main()
