#!/usr/bin/env python3
"""Writes consts.bend: Jubjub constants as Montgomery-form Fr literals (R = 2^256).

d = -10240/10241 and the generators (GroupHash outputs: spend-auth G, value-commitment
V and R, Pedersen-hash generators I_0..I_5) are computed by jj.py from the protocol spec
(BLAKE2s GroupHash with the URS). They are LABELLED CONSTANTS for the Bend code; the Rust
oracle's consts.txt is the cross-check (check_consts.py).

  python3 gen_consts.py
"""
import pathlib
import jj

here = pathlib.Path(__file__).resolve().parent
Q, RM = jj.Q, 1 << 256


def lit(x):
    v = x * RM % Q
    return "F.Fr{" + ", ".join(str((v >> (32 * i)) & 0xFFFFFFFF) for i in range(8)) + "}"


def aff(name, p, doc):
    u, v = p
    return f"# {doc}\ndef {name}() -> Aff:\n  Aff{{{lit(u)}, {lit(v)}}}\n"


g = jj.gens()
out = ["# GENERATED by gen_consts.py. Do not edit.", "import Base", "import ./fr.bend as F", "",
       "type Aff is Data:", "  Aff{u: F.Fr, v: F.Fr}", "",
       f"# d = -10240/10241 (Jubjub: -u^2 + v^2 = 1 + d u^2 v^2)\ndef d() -> F.Fr:\n  {lit(jj.D)}\n",
       f"def d2() -> F.Fr:\n  {lit(2 * jj.D % Q)}\n",
       aff("g_spendauth", g["G_SPENDAUTH"], "SpendAuthSig base G = FindGroupHash(\"Zcash_G_\", \"\")"),
       aff("v_cv", g["V_CV"], "value commitment value base V = FindGroupHash(\"Zcash_cv\", \"v\")"),
       aff("r_cv", g["R_CV"], "value commitment randomness base R = FindGroupHash(\"Zcash_cv\", \"r\") (binding sig base)")]
for i in range(3):
    out.append(aff(f"ph{i}", g[f"PH{i}"], f"Pedersen hash generator I_{i + 1} = FindGroupHash(\"Zcash_PH\", LE32({i}))"))
(here / "consts.bend").write_text("\n".join(out))
print("wrote consts.bend")
