#!/usr/bin/env python3
"""Table-based square root for Jubjub's base field (fr.bend), from research/decomp/gen.py.

research/decomp/gen.py implements Sarkar's algorithm (eprint 2020/1407, pasta_curves' sqrt-table) for
p - 1 = t * 2^32 with 5 as the non-residue. BLS12-381's r has the same shape (2-adicity
32, 5 a non-residue), so the generator applies with one change: x^((t-1)/2) uses fr.bend's
own sliding-window chain (pow_c3) instead of a pasta_curves addition chain. The Python
self-test of the algorithm runs on r before anything is written.

  python3 gen_sqrt.py [N]   -> fr_sqrt.bend
"""
import importlib.util
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("decomp_gen", here.parent.parent.parent / "research/decomp/gen.py")
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)

R_BLS = 0x73EDA753299D7D483339D80809A1D80553BDA402FFFE5BFEFFFFFFFF00000001
g.FIELDS["fr"] = dict(p=R_BLS, ty="Fr", mod="./fr.bend")
t = (R_BLS - 1) >> 32
# A placeholder chain (only its exponent is checked); pow_t is replaced by fr.bend's pow_c3.
g.CHAINS["fr"] = dict(pre={}, steps=[], tail=0, exp=(t - 1) // 2)
_orig = g.chain_exp
g.chain_exp = lambda c: c["exp"] if "exp" in c else _orig(c)

f = g.F("fr")
n = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
tot, sq = f.selftest(n)
print(f"fr: W = {g.W}, hash M = {f.hmul:#x}; python self-test {tot} inputs ({sq} squares) ok")
src = g.emit(f)
src, k = re.subn(r"# x\^\(\(t-1\)/2\): pasta_curves' addition chain.*?\ndef pow_t\(\+x: B\.Fr\) -> B\.Fr:\n(?:  .*\n)+",
                 "# x^((t-1)/2): fr.bend's sliding-window chain.\ndef pow_t(+x: B.Fr) -> B.Fr:\n  B.pow_c3(x)\n", src)
assert k == 1, "pow_t pattern"
src = src.replace("# GENERATED by research/decomp/gen.py. Do not edit.", "# GENERATED by zcash/sapling/jubjub/gen_sqrt.py (via research/decomp/gen.py). Do not edit.")
(here / "fr_sqrt.bend").write_text(src)
print("wrote fr_sqrt.bend")
