def limbs32(x, n):
    return [(x >> (32 * i)) & 0xFFFFFFFF for i in range(n)]


def limbs_u64(ls, n):
    return limbs32(sum(v << (64 * i) for i, v in enumerate(ls)), n)


class Gen:
    def __init__(self):
        self.lines, self.n = [], 0

    def var(self, expr):
        self.n += 1
        name = f"g{self.n}"
        self.lines.append(f"  +{name} = {expr}")
        return name

    def mul(self, a, b, a_const=False, b_const=False):
        """Schoolbook product of limb lists (strings: var names or int literals)."""
        prod = ["0"] * (len(a) + len(b))
        for i, ai in enumerate(a):
            carry = "0"
            for j, bj in enumerate(b):
                lo = self.var(f"({ai} * {bj} + {prod[i + j]} + {carry} : U32)")
                hi = self.var(f"I.mach({ai}, {bj}, {prod[i + j]}, {carry})")
                prod[i + j], carry = lo, hi
            prod[i + len(b)] = carry
        return prod

    def sub(self, a, b):
        out, borrow = [], "0"
        for ai, bi in zip(a, b):
            out.append(self.var(f"({ai} - {bi} - {borrow} : U32)"))
            borrow = self.var(f"I.subb({ai}, {bi}, {borrow})")
        return out

    def add_small(self, a, c):
        out = []
        for ai in a:
            out.append(self.var(f"({ai} + {c} : U32)"))
            c = self.var(f"I.addc({ai}, {c}, 0)")
        return out


def emit(name, c):
    g = Gen()
    k = [f"k{i}" for i in range(8)]
    G1, G2 = limbs_u64(c["G1"], 10), limbs_u64(c["G2"], 10)

    def round_mul_shift(G):
        prod = g.mul([str(x) for x in G], k)
        rnd = g.var(f"({prod[11]} >> 31n : U32)")
        return g.add_small(prod[12:16], rnd)

    c1 = round_mul_shift(G1)
    c2 = round_mul_shift(G2)
    lit = lambda v: [str(x) for x in limbs32(v, 4)]
    k1 = g.sub(g.sub(k, g.mul(c1, lit(c["V1A"]))[:8]), g.mul(c2, lit(c["V2A"]))[:8])
    k2 = g.sub(g.mul(c1, lit(c["V1B_NEG"]))[:8], g.mul(c2, lit(c["V2B"]))[:8])

    def signed(x):
        neg = g.var(f"({x[7]} >> 31n : U32)")
        inv = [g.var(f"({xi} .^. 4294967295 : U32)") for xi in x[:4]]
        mag_neg = g.add_small(inv, "1")
        mag = [g.var(f"U32.or(({mi} .&. (0 - {neg} : U32) : U32), ({xi} .&. ({neg} - 1 : U32) : U32))") for mi, xi in zip(mag_neg, x[:4])]
        return neg, mag

    n1, m1 = signed(k1)
    n2, m2 = signed(k2)
    zw = ", ".join(str(x) for x in limbs32(c["zeta"], 8))
    body = "\n".join(g.lines)
    return f"""# GENERATED by gen_glv.py. Do not edit.
# GLV scalar multiplication on {name}: k*P = k1*P + k2*phi(P), phi(x, y) = (zeta*x, y).
# Decomposition mirrors pasta_curves 0.6.1 glv.rs (Babai rounding at bit 384).
import Base
import ../../halo2/lib/words.bend as Wd
import ../../fast/intrinsics.bend as I
import {c['curve']} as V
import {c['base']} as B

# (neg1, |k1|, neg2, |k2|), magnitudes < 2^127 in the low four words.
type Split is Data:
  Split{{n1: U32, m1: Wd.W, n2: U32, m2: Wd.W}}

def split(k: Wd.W) -> Split:
  Wd.W{{+k0, +k1, +k2, +k3, +k4, +k5, +k6, +k7}} = k
{body}
  Split{{{n1}, Wd.W{{{m1[0]}, {m1[1]}, {m1[2]}, {m1[3]}, 0, 0, 0, 0}}, {n2}, Wd.W{{{m2[0]}, {m2[1]}, {m2[2]}, {m2[3]}, 0, 0, 0, 0}}}}

def zeta() -> B.{c['base_ty']}:
  B.from_words(Wd.W{{{zw}}})

def endo(p: V.Pt) -> V.Pt:
  V.Pt{{x, y, z}} = p
  V.Pt{{B.mul(x, zeta()), y, z}}

def neg_b(b: Bool, p: V.Pt) -> V.Pt:
  match b:
    case True{{}}:
      V.neg(p)
    case False{{}}:
      p

def neg_if(+n: U32, p: V.Pt) -> V.Pt:
  neg_b(U32.is_eq(n, 1), p)

# [0, Q, 2Q, ..., 15Q] (built highest-first, then reversed).
def mults(n: Nat, +q: V.Pt, +acc: V.Pt, out: +List<V.Pt>) -> +List<V.Pt>:
  match n:
    case 0n:
      out
    case 1n+k:
      mults(k, q, V.add(acc, q), acc <> out)

def table(+q: V.Pt) -> +List<V.Pt>:
  List.reverse(&2, V.Pt, mults(16n, q, V.identity(), Nil{{}}))

def nth(+d: Nat, xs: +List<V.Pt>) -> V.Pt:
  match d xs:
    case 0n Con{{+h, _}}:
      h
    case 1n+k Con{{_, t}}:
      nth(k, t)
    case _ _:
      V.identity()

def get(+t: +List<V.Pt>, +d: U32) -> V.Pt:
  nth(U32.to_nat(d), t)

def wget(+i: Nat, w: Wd.W) -> U32:
  match i w:
    case 0n Wd.W{{w0, _, _, _, _, _, _, _}}:
      w0
    case 1n Wd.W{{_, w1, _, _, _, _, _, _}}:
      w1
    case 2n Wd.W{{_, _, w2, _, _, _, _, _}}:
      w2
    case _ Wd.W{{_, _, _, w3, _, _, _, _}}:
      w3

# 4-bit digit number j (0 = least significant) of a 128-bit magnitude.
def digit(+j: Nat, +w: Wd.W) -> U32:
  +jj = U32.from_nat(j)
  ((wget(U32.to_nat((jj >> 3n : U32)), w) >> U32.to_nat(((jj .&. 7 : U32) << 2n : U32))) .&. 15 : U32)

def dbl4(p: V.Pt) -> V.Pt:
  V.double(V.double(V.double(V.double(p))))

# Straus ladder over digits j = n-1 .. 0 of both halves.
def ladder(+n: Nat, +t1: +List<V.Pt>, +t2: +List<V.Pt>, +m1: Wd.W, +m2: Wd.W, acc: V.Pt) -> V.Pt:
  match n:
    case 0n:
      acc
    case 1n+j:
      +a1 = V.add(dbl4(acc), get(t1, digit(j, m1)))
      ladder(j, t1, t2, m1, m2, V.add(a1, get(t2, digit(j, m2))))

def mul_split(+p: V.Pt, s: Split) -> V.Pt:
  Split{{+n1, +m1, +n2, +m2}} = s
  +p1 = neg_if(n1, p)
  +p2 = neg_if(n2, endo(p))
  ladder(32n, table(p1), table(p2), m1, m2, V.identity())

# k*P for a canonical scalar (8 little-endian words).
def mul(+p: V.Pt, k: Wd.W) -> V.Pt:
  mul_split(p, split(k))
"""


