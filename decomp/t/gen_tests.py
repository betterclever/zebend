#!/usr/bin/env python3
"""Emit t/sqrt_vs_pasta.bend and t/edges_{fp,fq}.txt (edge inputs, 32-byte LE hex).

The Bend program and `rust/ digest` compute the same thing from the same inputs:
  - edge lines: the normalized root (even canonical low bit) of every edge value, or "none";
  - per field: 2^D leaves x N items of xorshift words x = rw(s) (as field3's t/sqrt3_64) and
    their squares x^2; digest = wrapping sum over items of fold(xs(h ^ word)) over the 8 words
    of the normalized root (h starts at the item seed; a missing root folds 0xA5A5A5A5).
  The Bend side also counts disagreements with field3's own sqrt (up to sign).
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import gen  # noqa: E402

HERE = Path(__file__).resolve().parent


def edges(f):
    p, w = f.p, f.w
    rng = random.Random("edges-" + f.name)
    v = [0, 1, 2, 3, 4, 5, 7, p - 1, p - 2, p - 5, (p - 1) // 2, (p + 1) // 2, (1 << 254) - 1,
         p - (1 << 32), (1 << 32) % p, ((1 << 32) - 1) % p]
    v += [pow(w, 1 << k, p) for k in range(32)]                # orders 2^32 .. 2
    v += [pow(w, e, p) for e in (3, 5, (1 << 32) - 1, (1 << 31) + 1, (1 << 31) - 1, 6, 10)]
    for _ in range(24):                                          # max 2-adicity, mixed t-part
        r = rng.randrange(1, p)
        v.append(pow(w, rng.randrange(1 << 32), p) * r * r % p)
        v.append(pow(w, 2 * rng.randrange(1 << 31) + 1, p) * r * r % p)
    return v


def hexle(a):
    return a.to_bytes(32, "little").hex()


def words(a):
    return [(a >> (32 * i)) & 0xFFFFFFFF for i in range(8)]


def main():
    fs = {n: gen.F(n) for n in gen.FIELDS}
    out = ["# GENERATED by t/gen_tests.py. decomp table sqrt vs pasta_curves (rust/ digest).",
           "import Base",
           "import ../../halo2/lib/words.bend as Wd",
           "import ../../field3/fp64.bend as Fp",
           "import ../../field3/fq64.bend as Fq",
           "import ../fp_sqrt.bend as PS",
           "import ../fq_sqrt.bend as QS",
           "",
           "def xs(+s: U32) -> U32:",
           "  +a = (s .^. (s << 13n) : U32)",
           "  +b = (a .^. (a >> 17n) : U32)",
           "  (b .^. (b << 5n) : U32)",
           "",
           "def rw(+s: U32) -> Wd.W:",
           "  +s1 = xs(s)", "  +s2 = xs(s1)", "  +s3 = xs(s2)", "  +s4 = xs(s3)",
           "  +s5 = xs(s4)", "  +s6 = xs(s5)", "  +s7 = xs(s6)", "  +s8 = xs(s7)",
           "  Wd.W{s1, s2, s3, s4, s5, s6, s7, (s8 .&. 1073741823 : U32)}",
           "",
           "def next8(+s: U32) -> U32:",
           "  xs(xs(xs(xs(xs(xs(xs(xs(s))))))))",
           "",
           "def fold(+h: U32, w: Wd.W) -> U32:",
           "  Wd.W{a, b, c, d, e, f, g, k} = w",
           "  xs((xs((xs((xs((xs((xs((xs((xs((h .^. a : U32)) .^. b : U32)) .^. c : U32)) .^. d : U32)) .^. e : U32)) .^. f : U32)) .^. g : U32)) .^. k : U32))",
           "",
           "type D is Data:",
           "  D{sum: U32, bad: U32, sq: U32}",
           "",
           "def dadd(a: D, b: D) -> D:",
           "  D{+x, +y, +z} = a",
           "  D{+u, +v, +w} = b",
           "  D{(x + u : U32), (y + v : U32), (z + w : U32)}",
           "",
           ]
    for n, f in fs.items():
        T, M, O = f.ty, ("PS" if n == "fp" else "QS"), f.ty
        out += [
            f"def {n}_norm(+r: {O}.{T}) -> {O}.{T}:",
            f"  {O}.sel({O}.low_bit(r), {O}.neg(r), r)",
            "",
            f"def {n}_hash(+h: U32, m: Maybe<&2, {O}.{T}>) -> U32:",
            "  match m:",
            "    case Some{+r}:",
            f"      fold(h, {O}.to_words({n}_norm(r)))",
            "    case None{}:",
            "      xs((h .^. 2779096485 : U32))",
            "",
            f"def {n}_show(m: Maybe<&2, {O}.{T}>) -> String:",
            "  match m:",
            "    case Some{+r}:",
            f"      Wd.hex({O}.to_words({n}_norm(r)))",
            "    case None{}:",
            '      "none"',
            "",
            "# 1 if the two results disagree (presence, or root up to sign).",
            f"def {n}_diff(a: Maybe<&2, {O}.{T}>, b: Maybe<&2, {O}.{T}>) -> U32:",
            "  match a b:",
            "    case Some{+r} Some{+s}:",
            f"      Bool.to_u32(Bool.not({O}.is_eq({n}_norm(r), {n}_norm(s))))",
            "    case None{} None{}:",
            "      0",
            "    case _ _:",
            "      1",
            "",
            f"def {n}_d1(+s: U32, +x: {O}.{T}) -> D:",
            f"  +m = {M}.sqrt(x)",
            f"  +sq = Maybe.is_some(&2, {O}.{T}, m)",
            f"  D{{{n}_hash(s, m), {n}_diff(m, {O}.sqrt(x)), Bool.to_u32(sq)}}",
            "",
            f"def {n}_item(+s: U32) -> D:",
            f"  +x = {O}.from_words(rw(s))",
            f"  dadd({n}_d1(s, x), {n}_d1((s .^. 1 : U32), {O}.sqr(x)))",
            "",
            f"def {n}_run(n: Nat, +s: U32, a: D) -> D:",
            "  match n:",
            "    case 0n:",
            "      a",
            "    case 1n+k:",
            f"      {n}_run(k, next8(s), dadd(a, {n}_item(s)))",
            "",
            f"def {n}_par(+d: Nat, +seed: U32, +n: Nat) -> D:",
            "  match d:",
            "    case 0n:",
            f"      {n}_run(n, (seed * 2654435761 + 777 : U32), D{{0, 0, 0}})",
            "    case 1n+p:",
            f"      a b = {n}_par(p, (seed * 2 : U32), n) {n}_par(p, (seed * 2 + 1 : U32), n)",
            "      dadd(a, b)",
            "",
            f"def {n}_edges() -> +List<Wd.W>:",
            "  " + " <> ".join(f"Wd.W{{{', '.join(map(str, words(a)))}}}" for a in edges(f)) + " <> Nil{}",
            "",
            f"def {n}_edge_lines(ws: +List<Wd.W>) -> +List<String>:",
            "  match ws:",
            "    case Con{+w, +t}:",
            f"      +x = {O}.from_words(w)",
            f"      (\"{n} edge \" ++ Wd.hex(w) ++ \" \" ++ {n}_show({M}.sqrt(x)) ++ \" field3 \" ++ U32.show({n}_diff({M}.sqrt(x), {O}.sqrt(x)))) <> {n}_edge_lines(t)",
            "    case Nil{}:",
            "      Nil{}",
            "",
        ]
        (HERE / f"edges_{n}.txt").write_text("".join(hexle(a) + "\n" for a in edges(f)))
    out += [
        "def show(+tag: String, a: D) -> String:",
        "  D{+s, +b, +q} = a",
        '  tag ++ " digest " ++ U32.show(s) ++ " squares " ++ U32.show(q) ++ " field3_disagree " ++ U32.show(b)',
        "",
        "def print_all(ls: +List<String>) -> IO(Unit):",
        "  match ls:",
        "    case Con{l, t}:",
        "      do IO<Unit>:",
        "        IO.print(l)",
        "        print_all(t)",
        "    case Nil{}:",
        "      IO.pure(Unit, Unit{})",
        "",
        "# argv-free: depth D and per-leaf N are fixed here (2^10 x 2^10 = 1,048,576 x and x^2 per field).",
        "def main() -> IO(Unit):",
        "  do IO<Unit>:",
        "    print_all(fp_edge_lines(fp_edges()))",
        "    print_all(fq_edge_lines(fq_edges()))",
        '    IO.print(show("fp", fp_par(10n, 1, 1024n)))',
        '    IO.print(show("fq", fq_par(10n, 2, 1024n)))',
        "",
    ]
    (HERE / "sqrt_vs_pasta.bend").write_text("\n".join(out))
    print("wrote sqrt_vs_pasta.bend, edges_fp.txt, edges_fq.txt",
          {n: len(edges(f)) for n, f in fs.items()})


if __name__ == "__main__":
    main()
